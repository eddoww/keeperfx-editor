#[derive(Clone, Debug, PartialEq)]
pub enum UpdateStatus {
    UpToDate,
    /// A newer file exists on the Workshop.
    Available {
        file: FileEntry,
        reason: String,
    },
    /// Not installed from the Workshop, or the remote has no usable file.
    Unknown(String),
}

/// Compare the installed file (manifest) with the Workshop's newest non-broken file: a different
/// file id that is newer by id or date, or the same id with a different size label.
pub fn check_update(m: &Manifest, remote: &crate::model::ItemDetail) -> UpdateStatus {
    let Some(item) = &m.item else {
        return UpdateStatus::Unknown("not installed from the Workshop".into());
    };
    let Some(latest) = remote.latest_file() else {
        return UpdateStatus::Unknown("the Workshop item has no downloadable file".into());
    };
    if latest.id != item.file_id {
        if latest.id > item.file_id || latest.date > item.file_date {
            return UpdateStatus::Available {
                file: latest.clone(),
                reason: format!(
                    "newer file {} ({}, {}) than the installed {} ({})",
                    latest.name, latest.date, latest.size_label, item.file_name, item.file_date
                ),
            };
        }
        return UpdateStatus::UpToDate;
    }
    if !latest.size_label.is_empty()
        && !item.file_size_label.is_empty()
        && latest.size_label != item.file_size_label
    {
        return UpdateStatus::Available {
            file: latest.clone(),
            reason: format!(
                "the file was replaced in place ({} -> {})",
                item.file_size_label, latest.size_label
            ),
        };
    }
    UpdateStatus::UpToDate
}
