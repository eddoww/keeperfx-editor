struct Planner<'a> {
    install: &'a Path,
    insp: &'a Inspected,
    opts: &'a PlanOptions,
    plan: InstallPlan,
    /// (dest dir lower-case, number) already taken by this plan
    taken: BTreeSet<(String, u32)>,
}

impl Planner<'_> {
    fn full(&self, p: &str) -> String {
        match &self.insp.class.wrapper {
            Some(w) => format!("{w}/{p}"),
            None => p.to_string(),
        }
    }
    fn size_of(&self, stripped: &str) -> u64 {
        let f = self.full(stripped);
        self.insp
            .listing
            .files()
            .find(|e| e.path == f)
            .map_or(0, |e| e.size)
    }
    fn peek(&self, stripped: &str) -> Option<&Vec<u8>> {
        self.insp.peeked.get(&self.full(stripped))
    }

    fn push(&mut self, dest: String, source: Source, size: u64, note: Option<String>) {
        // resolve the destination spelling against the install
        let (dest, exists) = resolve_ci(self.install, &dest);
        let action = if !exists {
            Action::Create
        } else {
            match self.opts.conflict {
                Conflict::Overwrite => Action::Overwrite,
                _ => Action::Skip,
            }
        };
        let note = if exists && action == Action::Skip {
            Some("already exists, kept".to_string())
        } else {
            note
        };
        if self
            .plan
            .items
            .iter()
            .any(|i| i.dest.eq_ignore_ascii_case(&dest))
        {
            self.plan.warnings.push(format!(
                "{dest} appears twice in the archive; the first one is used"
            ));
            return;
        }
        self.plan.items.push(PlanItem {
            dest,
            source,
            size,
            action,
            note,
        });
    }

    /// Install `class.levels` group `g` into `dest_dir`.
    fn place_group(&mut self, g: &LevelGroup, dest_dir: &str, rooted: bool) {
        let resolved_dir = resolve_ci(self.install, dest_dir).0;
        let dir_path = self.install.join(&resolved_dir);
        let existing = level_files_in(&dir_path);
        let dir_key = resolved_dir.to_ascii_lowercase();
        let mut mapping: BTreeMap<u32, u32> = BTreeMap::new();
        let mut skipped: BTreeSet<u32> = BTreeSet::new();
        for &n in &g.numbers {
            let conflict = existing.contains(&n) || self.taken.contains(&(dir_key.clone(), n));
            if !conflict {
                self.taken.insert((dir_key.clone(), n));
                continue;
            }
            match self.opts.conflict {
                Conflict::Overwrite if existing.contains(&n) => {
                    self.plan.warnings.push(format!(
                        "level {n} in {resolved_dir} is overwritten (files of the \
                            old level with other names stay)"
                    ));
                    self.taken.insert((dir_key.clone(), n));
                }
                Conflict::Skip => {
                    skipped.insert(n);
                    self.plan.warnings.push(format!(
                        "level {n} skipped: {resolved_dir} already has a level {n}"
                    ));
                }
                _ => {
                    let mut to = n;
                    loop {
                        to = if to >= MAX_LEVEL { 1 } else { to + 1 };
                        if to == n {
                            break;
                        }
                        if !existing.contains(&to)
                            && !self.taken.contains(&(dir_key.clone(), to))
                            && !g.numbers.contains(&to)
                        {
                            break;
                        }
                    }
                    if to == n {
                        skipped.insert(n);
                        self.plan
                            .blocked
                            .push(format!("no free level number in {resolved_dir}"));
                    } else {
                        self.taken.insert((dir_key.clone(), to));
                        mapping.insert(n, to);
                        self.plan.renumbered.push(Renumber {
                            dir: resolved_dir.clone(),
                            from: n,
                            to,
                        });
                    }
                }
            }
        }
        // files of the group folder
        let prefix = if g.dir.is_empty() {
            String::new()
        } else {
            format!("{}/", g.dir)
        };
        let entries: Vec<String> = self.insp.listing.files().map(|e| e.path.clone()).collect();
        let mut has_overview: BTreeSet<u32> = BTreeSet::new();
        for full_path in entries {
            let Some(stripped) = self.strip_wrapper(&full_path) else {
                continue;
            };
            let Some(rest) = stripped.strip_prefix(&prefix) else {
                continue;
            };
            if rest.contains('/') {
                continue; // subfolders of a level folder are handled by the rooted pass
            }
            let lower = rest.to_ascii_lowercase();
            let num = crate::classify::level_number(rest);
            match num {
                Some(n) if g.numbers.contains(&n) => {
                    if skipped.contains(&n) {
                        continue;
                    }
                    if lower.ends_with(".lof") || lower.ends_with(".lif") {
                        has_overview.insert(n);
                    }
                    let to = mapping.get(&n).copied().unwrap_or(n);
                    let name = if to != n {
                        renumber_name(rest, to)
                    } else {
                        rest.to_string()
                    };
                    let size = self.size_of(&stripped);
                    let (src, note) = if to != n && lower.ends_with(".lif") {
                        (
                            Source::LifRenumber {
                                entry: full_path.clone(),
                                from: n,
                                to,
                            },
                            Some(format!("renumbered {n} to {to}")),
                        )
                    } else {
                        (
                            Source::Entry(full_path.clone()),
                            (to != n).then(|| format!("renumbered {n} to {to}")),
                        )
                    };
                    self.push(format!("{resolved_dir}/{name}"), src, size, note);
                }
                _ => {
                    if rooted {
                        let size = self.size_of(&stripped);
                        self.push(
                            format!("{resolved_dir}/{rest}"),
                            Source::Entry(full_path.clone()),
                            size,
                            None,
                        );
                    }
                }
            }
        }
        for &n in &g.numbers {
            if skipped.contains(&n) {
                continue;
            }
            let to = mapping.get(&n).copied().unwrap_or(n);
            let mut disp = self.opts.name.clone();
            if self
                .insp
                .class
                .levels
                .iter()
                .map(|x| x.numbers.len())
                .sum::<usize>()
                > 1
            {
                disp = format!("{} {}", self.opts.name, to);
            }
            if !has_overview.contains(&n) {
                if g.multiplayer {
                    self.plan.warnings.push(format!(
                        "level {to}: multiplayer map without a .lof; it will not \
                            show in the multiplayer list"
                    ));
                } else {
                    // free play needs a .lif or .lof: generate a .lif
                    let bytes = kfx_formats::cfg::latin1_encode(&format!("{to}, {disp}\n"));
                    self.push(
                        format!("{resolved_dir}/map{to:05}.lif"),
                        Source::Generated(bytes.clone()),
                        bytes.len() as u64,
                        Some("generated (the archive has no .lof/.lif)".into()),
                    );
                }
            }
            self.plan.levels.push((resolved_dir.clone(), to, disp));
        }
    }

    fn strip_wrapper(&self, full_path: &str) -> Option<String> {
        match &self.insp.class.wrapper {
            Some(w) => full_path.strip_prefix(&format!("{w}/")).map(String::from),
            None => Some(full_path.to_string()),
        }
    }

    fn stripped_files(&self) -> Vec<(String, String)> {
        // (full archive path, stripped path)
        self.insp
            .listing
            .files()
            .filter_map(|e| self.strip_wrapper(&e.path).map(|s| (e.path.clone(), s)))
            .filter(|(_, s)| !s.is_empty())
            .collect()
    }
}

/// Build the install plan for an inspected archive.
pub fn plan(
    install: &Path,
    archive: &Path,
    insp: &Inspected,
    opts: &PlanOptions,
) -> Result<InstallPlan> {
    let class = &insp.class;
    let archive_sha256 = crate::util::sha256_file(archive).map_err(|e| Error::io(archive, e))?;
    let mut p = Planner {
        install,
        insp,
        opts,
        plan: InstallPlan {
            archive: archive.to_path_buf(),
            name: opts.name.clone(),
            kind: class.kind,
            item: opts.item.clone(),
            items: vec![],
            load_order: vec![],
            creates_load_order: false,
            renumbered: vec![],
            levels: vec![],
            campaigns: vec![],
            warnings: vec![],
            blocked: vec![],
            archive_sha256,
            strip_prefix: class
                .wrapper
                .as_ref()
                .map(|w| format!("{w}/"))
                .unwrap_or_default(),
        },
        taken: BTreeSet::new(),
    };
    if !class.unsafe_entries.is_empty() {
        for u in class.unsafe_entries.iter().take(5) {
            p.plan.blocked.push(format!("unsafe archive entry: {u}"));
        }
    }
    if !install.is_dir() {
        p.plan
            .blocked
            .push(format!("{} is not a folder", install.display()));
    }
    let files = p.stripped_files();
    let rooted = class.layout == Layout::Rooted;
    let slug_name = slug(&opts.name);
    let overwrite = opts.conflict == Conflict::Overwrite;

    if rooted {
        // levels: group-aware (renumbering); everything else under the roots as is
        for g in &class.levels {
            let dest = g.dir.clone();
            p.place_group(g, &dest, true);
        }
        let group_dirs: BTreeSet<String> = class
            .levels
            .iter()
            .map(|g| g.dir.to_ascii_lowercase())
            .collect();
        let mut mod_names = BTreeSet::new();
        for (full, s) in &files {
            let parts: Vec<&str> = s.split('/').collect();
            let root = parts[0].to_ascii_lowercase();
            if parts.len() < 2
                || !["levels", "campgns", "mods", "multiplayer"].contains(&root.as_str())
            {
                continue;
            }
            let (dir, name) = split_dir(s);
            if group_dirs.contains(&dir.to_ascii_lowercase())
                && (crate::classify::level_number(name).is_some()
                    || class.levels.iter().any(|g| g.dir.eq_ignore_ascii_case(dir)))
            {
                continue; // placed by place_group
            }
            if s.eq_ignore_ascii_case(LOAD_ORDER) || s.eq_ignore_ascii_case("mods/_load_order.cfg")
            {
                p.plan.warnings.push(format!(
                    "{s} of the archive is not installed; its mods are added to \
                        your own load_order.cfg"
                ));
                if root == "mods" {
                    continue;
                }
            }
            if root == "mods" && parts.len() >= 3 {
                mod_names.insert(parts[1].to_string());
            }
            let size = p.size_of(s);
            p.push(s.clone(), Source::Entry(full.clone()), size, None);
        }
        // whole-folder conflicts of campaigns and mods
        for c in &class.campaigns {
            let name = c.rsplit('/').next().unwrap_or(c).to_string();
            p.plan.campaigns.push(format!("campgns/{name}"));
            if !overwrite && resolve_ci(install, &format!("campgns/{name}")).1 {
                p.plan.blocked.push(format!(
                    "campaign campgns/{name} is already installed; uninstall it \
                        first or choose Overwrite"
                ));
            }
        }
        for m in &mod_names {
            if !overwrite && resolve_ci(install, &format!("mods/{m}")).1 {
                p.plan.blocked.push(format!(
                    "mod mods/{m} is already installed; uninstall it first or choose Overwrite"
                ));
            }
        }
        for pk in &class.packs {
            let name = pk.rsplit('/').next().unwrap_or(pk);
            let root = pk.split('/').next().unwrap_or("levels");
            if !overwrite && resolve_ci(install, &format!("{root}/{name}")).1 {
                p.plan.blocked.push(format!(
                    "pack {root}/{name} is already installed; uninstall it first \
                        or choose Overwrite"
                ));
            }
        }
        add_mods(&mut p, &mod_names.into_iter().collect::<Vec<_>>());
    } else {
        match class.kind {
            Kind::Level | Kind::MapPack => {
                plan_loose_levels(&mut p, &files, &slug_name);
            }
            Kind::Campaign => {
                plan_loose_campaign(&mut p, &files);
            }
            Kind::Mod | Kind::CreaturePack => {
                plan_loose_mod(&mut p, &files, &slug_name);
            }
            Kind::Other => {
                p.plan.warnings.push(
                    "not game content: the files are only unpacked into \
                        workshop_extras/ (the game does not load them)"
                        .into(),
                );
                let base = unique_name(install, "workshop_extras", &slug_name, opts.conflict);
                for (full, s) in &files {
                    let size = p.size_of(s);
                    p.push(
                        format!("workshop_extras/{base}/{s}"),
                        Source::Entry(full.clone()),
                        size,
                        None,
                    );
                }
            }
        }
    }
    if p.plan.items.iter().all(|i| i.action == Action::Skip) && p.plan.blocked.is_empty() {
        p.plan
            .blocked
            .push("nothing to install (every file already exists or was skipped)".into());
    }
    Ok(p.plan)
}

fn unique_name(install: &Path, parent: &str, base: &str, conflict: Conflict) -> String {
    if conflict == Conflict::Overwrite || !resolve_ci(install, &format!("{parent}/{base}")).1 {
        return base.to_string();
    }
    (2..1000)
        .map(|n| format!("{base}_{n}"))
        .find(|c| !resolve_ci(install, &format!("{parent}/{c}")).1)
        .unwrap_or_else(|| base.to_string())
}

fn plan_loose_levels(p: &mut Planner, files: &[(String, String)], slug_name: &str) {
    let class = &p.insp.class;
    let multi_groups: Vec<&LevelGroup> = class.levels.iter().filter(|g| g.multiplayer).collect();
    let single_groups: Vec<&LevelGroup> = class.levels.iter().filter(|g| !g.multiplayer).collect();
    let kind = class.kind;
    let wrapper = class.wrapper.clone();
    // (the survey's most downloaded multiplayer maps use multiplayer/modern when the install has
    // multiplayer/modern.cfg; campgns/keeporig is the older rule)
    for g in multi_groups.clone() {
        if resolve_ci(p.install, "multiplayer/modern.cfg").1 {
            p.place_group(g, "multiplayer/modern", false);
        } else if resolve_ci(p.install, "campgns/keeporig").1 {
            p.place_group(g, "campgns/keeporig", false);
        } else {
            p.plan.blocked.push(
                "multiplayer maps go to multiplayer/modern or \
                    campgns/keeporig, and this install has neither"
                    .into(),
            );
        }
    }
    if !single_groups.is_empty() {
        // a wrapper folder named like an existing pack folder means "this goes into that pack"
        let existing = existing_packs(p.install);
        let target = match (&p.opts.pack_target, &wrapper) {
            (Some(t), _) => t.clone(),
            (None, Some(w)) if existing.iter().any(|e| e.eq_ignore_ascii_case(w)) => {
                PackTarget::Existing(
                    existing
                        .iter()
                        .find(|e| e.eq_ignore_ascii_case(w))
                        .cloned()
                        .unwrap_or_default(),
                )
            }
            _ => default_pack_target(p.install, kind, &p.opts.name),
        };
        let folder = match &target {
            PackTarget::Existing(n) => n.clone(),
            PackTarget::New(n) => {
                let n = unique_name(p.install, "levels", &slug(n), p.opts.conflict);
                let cfg_dest = format!("levels/{n}.cfg");
                let text = new_pack_cfg(p.install, &p.opts.name, &n);
                p.plan.items.push(PlanItem {
                    dest: cfg_dest,
                    size: text.len() as u64,
                    source: Source::Generated(text),
                    action: Action::Create,
                    note: Some("new map pack configuration".into()),
                });
                n
            }
        };
        if let PackTarget::Existing(n) = &target {
            if !resolve_ci(p.install, &format!("levels/{n}")).1 {
                p.plan
                    .warnings
                    .push(format!("levels/{n} does not exist yet; it is created"));
            }
        }
        let dest = format!("levels/{folder}");
        for g in single_groups {
            p.place_group(g, &dest, false);
        }
    }
    let _ = (files, slug_name);
}

fn new_pack_cfg(install: &Path, title: &str, folder: &str) -> Vec<u8> {
    // base it on the shipped personal pack (has the [strings] the GUI needs), else a minimal one
    let (path, _) = resolve_ci(install, "levels/personal.cfg");
    let template = std::fs::read(install.join(path))
        .ok()
        .map(|b| kfx_formats::cfg::latin1_decode(&b));
    let text = match template {
        Some(t) => {
            let nl = nl_of(&t);
            let mut out = vec![];
            for l in t.lines() {
                let u = l.trim_start().to_ascii_uppercase();
                if u.starts_with("NAME_TEXT_ID") {
                    continue;
                } else if u.starts_with("NAME") && u[4..].trim_start().starts_with('=') {
                    out.push(format!("NAME = {title}"));
                } else if u.starts_with("LEVELS_LOCATION") {
                    out.push(format!("LEVELS_LOCATION = levels/{folder}"));
                } else if u.starts_with("HIGH_SCORES") {
                    out.push(format!("HIGH_SCORES = 9999 scr_{folder}.dat"));
                } else {
                    out.push(l.to_string());
                }
            }
            out.join(nl) + nl
        }
        None => format!(
            "; KeeperFX Mappack file (generated by the KeeperFX editor)\n\
                \n[common]\nNAME = {title}\nLEVELS_LOCATION = levels/{folder}\nHIGH_SCORES = \
                9999 scr_{folder}.dat\nHUMAN_PLAYER = RED\n\n[strings]\nENG = \
                fxdata/gtext_eng.dat\n"
        ),
    };
    kfx_formats::cfg::latin1_encode(&text)
}

fn plan_loose_campaign(p: &mut Planner, files: &[(String, String)]) {
    let class_campaigns = p.insp.class.campaigns.clone();
    let packs = p.insp.class.packs.clone();
    let overwrite = p.opts.conflict == Conflict::Overwrite;
    let mut dirs: BTreeSet<String> = BTreeSet::new();
    for (_, s) in files {
        if let Some((top, _)) = s.split_once('/') {
            dirs.insert(top.to_string());
        }
    }
    for cfg in &class_campaigns {
        if !overwrite && resolve_ci(p.install, &format!("campgns/{cfg}")).1 {
            p.plan.blocked.push(format!(
                "campaign campgns/{cfg} is already installed; uninstall it \
                    first or choose Overwrite"
            ));
        }
        p.plan.campaigns.push(format!("campgns/{cfg}"));
        // referenced folders that are neither in the archive nor in the install
        if let Some(b) = p.peek(cfg) {
            let c = kfx_formats::campaign::Campaign::parse(b).common();
            for loc in [
                &c.levels_location,
                &c.land_location,
                &c.creatures_location,
                &c.configs_location,
            ]
            .into_iter()
            .flatten()
            {
                let base = loc
                    .trim_matches('/')
                    .rsplit('/')
                    .next()
                    .unwrap_or("")
                    .to_string();
                if !base.is_empty()
                    && !dirs.iter().any(|d| d.eq_ignore_ascii_case(&base))
                    && !resolve_ci(p.install, loc.trim_matches('/')).1
                {
                    p.plan.warnings.push(format!(
                        "the campaign refers to {loc}, which is neither in the \
                            archive nor in the install"
                    ));
                }
            }
        }
    }
    let target_root = if class_campaigns.is_empty() && !packs.is_empty() {
        "levels"
    } else {
        "campgns"
    };
    for (full, s) in files {
        let size = p.size_of(s);
        if s.contains('/') || s.to_ascii_lowercase().ends_with(".cfg") {
            p.push(
                format!("{target_root}/{s}"),
                Source::Entry(full.clone()),
                size,
                None,
            );
        }
    }
}

fn plan_loose_mod(p: &mut Planner, files: &[(String, String)], slug_name: &str) {
    let kind = p.insp.class.kind;
    let base = p
        .insp
        .class
        .wrapper
        .as_ref()
        .map(|w| w.rsplit('/').next().unwrap_or(w).to_string())
        .filter(|w| !w.is_empty() && !w.contains(' '))
        .unwrap_or_else(|| slug_name.to_string());
    let name = unique_name(p.install, "mods", &base, p.opts.conflict);
    let sprite = p.insp.class.sprite_content;
    let mut has_mod_cfg = false;
    let mut repack: Vec<String> = vec![];
    let mut mod_cfg_text: Option<String> = None;
    for (full, s) in files {
        let lower = s.to_ascii_lowercase();
        let (dir, fname) = split_dir(s);
        let size = p.size_of(s);
        let dest: Option<String> = if lower == "mod.cfg" {
            has_mod_cfg = true;
            mod_cfg_text = p.peek(s).map(|b| kfx_formats::cfg::latin1_decode(b));
            Some(format!("mods/{name}/mod.cfg"))
        } else if sprite
            && (lower == "sprites.json"
                || lower == "icons.json"
                || !dir.is_empty()
                    && !lower.starts_with("@cfg/")
                    && !lower.starts_with("fxdata/")
                    && !lower.starts_with("creatrs/"))
        {
            repack.push(full.clone());
            None
        } else if let Some(r) = lower.strip_prefix("@cfg/") {
            Some(format!("mods/{name}/creatrs/{}", &s[s.len() - r.len()..]))
        } else if dir.is_empty() {
            let ext = fname
                .rsplit_once('.')
                .map(|x| x.1.to_ascii_lowercase())
                .unwrap_or_default();
            match ext.as_str() {
                "cfg" if crate::classify::FXDATA_CFG.contains(&lower.as_str()) => {
                    Some(format!("mods/{name}/fxdata/{fname}"))
                }
                "cfg" => Some(format!("mods/{name}/creatrs/{fname}")),
                "zip" | "toml" | "dat" | "lua" => Some(format!("mods/{name}/fxdata/{fname}")),
                _ => {
                    p.plan
                        .warnings
                        .push(format!("{s} is not a game file and is not installed"));
                    None
                }
            }
        } else {
            // folders: fxdata/ and creatrs/ stay, cfgs/configs -> fxdata, crtr -> creatrs
            let (top, rest) = s.split_once('/').unwrap_or((s, ""));
            match top.to_ascii_lowercase().as_str() {
                "fxdata" | "creatrs" => Some(format!("mods/{name}/{s}")),
                "cfgs" | "cfg" | "configs" => Some(format!("mods/{name}/fxdata/{rest}")),
                "crtr" => Some(format!("mods/{name}/creatrs/{rest}")),
                _ => {
                    p.plan.warnings.push(format!(
                        "{s} is outside the folders a mod can use and is not installed"
                    ));
                    None
                }
            }
        };
        if let Some(d) = dest {
            p.push(d, Source::Entry(full.clone()), size, None);
        }
    }
    if !repack.is_empty() {
        let total: u64 = repack
            .iter()
            .map(|f| {
                p.insp
                    .listing
                    .files()
                    .find(|e| &e.path == f)
                    .map_or(0, |e| e.size)
            })
            .sum();
        p.push(
            format!("mods/{name}/fxdata/{name}.zip"),
            Source::Repack(repack),
            total,
            Some("sprite frames repacked into one sprite zip".into()),
        );
    }
    if !has_mod_cfg {
        let stage = p
            .opts
            .load_stage
            .clone()
            .unwrap_or_else(|| "after_base".into());
        let id_line = p
            .opts
            .item
            .as_ref()
            .map(|i| format!("\n[web]\nKfxNetWorkshopItemId = {}\n", i.id))
            .unwrap_or_default();
        let text = format!(
            "[mod]\nName = {}\nDescription = Installed from the KeeperFX \
                Workshop by the KeeperFX editor\nVersion = 1.0\nDefaultLoadOrder = {stage}\n{id_line}",
            p.opts.name
        );
        p.push(
            format!("mods/{name}/mod.cfg"),
            Source::Generated(text.into_bytes()),
            0,
            Some("generated".into()),
        );
    }
    if kind == Kind::CreaturePack {
        p.plan.warnings.push(
            "a creature only appears in a level when a script or \
                campaign uses it; the mod makes its configuration and sprites available"
                .into(),
        );
    }
    let stage_from_cfg = mod_cfg_text
        .as_deref()
        .and_then(|t| mod_cfg_value(t, "DefaultLoadOrder"));
    add_mods_with(p, &[name], stage_from_cfg);
}

fn add_mods(p: &mut Planner, names: &[String]) {
    // each mod's own mod.cfg may state the stage
    for n in names {
        let cfg = p
            .peek(&format!("mods/{n}/mod.cfg"))
            .map(|b| kfx_formats::cfg::latin1_decode(b));
        let stage = cfg
            .as_deref()
            .and_then(|t| mod_cfg_value(t, "DefaultLoadOrder"));
        add_mods_with(p, std::slice::from_ref(n), stage);
    }
}

fn add_mods_with(p: &mut Planner, names: &[String], stage: Option<String>) {
    if !p.opts.enable_mods {
        return;
    }
    let stage = stage
        .map(|s| s.to_ascii_lowercase())
        .filter(|s| STAGES.contains(&s.as_str()))
        .or_else(|| p.opts.load_stage.clone())
        .unwrap_or_else(|| "after_base".into());
    let (lo, exists) = resolve_ci(p.install, LOAD_ORDER);
    let text = if exists {
        std::fs::read(p.install.join(&lo))
            .ok()
            .map(|b| kfx_formats::cfg::latin1_decode(&b))
    } else {
        None
    };
    p.plan.creates_load_order = text.is_none();
    for n in names {
        if n.len() >= 64 {
            p.plan.blocked.push(format!(
                "mod name {n} is too long for load_order.cfg (63 bytes max)"
            ));
            continue;
        }
        let listed = text
            .as_deref()
            .is_some_and(|t| listed_anywhere(t, &stage, n));
        if let Some(t) = &text {
            if !listed && load_order_mods(t, &stage).len() >= MOD_ITEM_MAX {
                p.plan.blocked.push(format!(
                    "[{stage}] in load_order.cfg already lists {MOD_ITEM_MAX} \
                        mods (the game's limit)"
                ));
            }
        }
        p.plan.load_order.push(LoadOrderEntry {
            stage: stage.clone(),
            name: n.clone(),
            already_listed: listed,
        });
    }
}

