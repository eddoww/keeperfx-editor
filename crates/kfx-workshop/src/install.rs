//! Install plans, transactional apply, uninstall manifests, update checks.
//!
//! # Where things go (`src/config_campaigns.c`, `src/config_mods.c`)
//!
//! * level pack: `levels/<name>.cfg` + the folder named by its `LEVELS_LOCATION`
//!   (`levels/<name>/mapNNNNN.*`); free-play levels need a `.lif` or `.lof`
//! * campaign: `campgns/<name>.cfg` + its `*_LOCATION` folders
//! * multiplayer map: `.lof` with `KIND = MULTI` in `campgns/keeporig/` (wiki: Playing Custom Maps)
//! * mod: `mods/<name>/{fxdata,creatrs,...}` + a line in `mods/load_order.cfg` (`[after_base]`,
//!   `[after_campaign]`, `[after_map]`); `mods/_load_order.cfg` is a disabled example
//!
//! # Safety
//!
//! A plan never overwrites a file unless its [`Action`] is [`Action::Overwrite`], which is only
//! chosen with [`Conflict::Overwrite`]. Applying writes each destination folder through
//! [`kfx_formats::atomic::SaveTransaction`] (all or nothing per folder); folders already
//! committed are rolled back when a later one fails. Overwritten files and `load_order.cfg` are
//! first copied to the [`Store`], and the manifest (written last) lets [`uninstall`] restore the
//! previous state; files the user changed since the install are kept (reported) unless forced.

