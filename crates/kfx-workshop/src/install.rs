/// Which Workshop item/file an install came from (for the manifest and update checks).
#[derive(Clone, Debug, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct ItemRef {
    pub id: u32,
    pub title: String,
    pub slug: String,
    pub file_id: u32,
    pub file_name: String,
    pub file_size: u64,
    pub file_size_label: String,
    pub file_date: String,
}

impl ItemRef {
    pub fn from_file(id: u32, title: &str, slug: &str, f: &FileEntry) -> ItemRef {
        ItemRef {
            id,
            title: title.into(),
            slug: slug.into(),
            file_id: f.id,
            file_name: f.name.clone(),
            file_size: f.size,
            file_size_label: f.size_label.clone(),
            file_date: f.date.clone(),
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PackTarget {
    /// An existing level folder, `levels/<name>`.
    Existing(String),
    /// A new pack: `levels/<name>/` and a generated `levels/<name>.cfg`.
    New(String),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum Conflict {
    /// Give conflicting levels a free number (and packs/mods a free name); keep every existing
    /// file.
    #[default]
    Renumber,
    /// Replace existing files (the plan lists each one; they are backed up and restored on
    /// uninstall).
    Overwrite,
    /// Leave conflicting levels / files alone.
    Skip,
}

#[derive(Clone, Debug)]
pub struct PlanOptions {
    /// Display / folder name (item title or archive name).
    pub name: String,
    pub item: Option<ItemRef>,
    /// For loose single levels and packs; `None` picks [`default_pack_target`].
    pub pack_target: Option<PackTarget>,
    pub conflict: Conflict,
    /// Add mods to `mods/load_order.cfg`.
    pub enable_mods: bool,
    /// Load-order block when the mod does not say (`DefaultLoadOrder` in `mod.cfg`); default
    /// `after_base`.
    pub load_stage: Option<String>,
}

impl PlanOptions {
    pub fn new(name: &str) -> Self {
        PlanOptions {
            name: name.to_string(),
            item: None,
            pack_target: None,
            conflict: Conflict::Renumber,
            enable_mods: true,
            load_stage: None,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Source {
    /// A file of the archive.
    Entry(String),
    /// The archive file itself (a sprite zip installed as it is).
    Raw,
    /// Entries repacked into one zip (unpacked sprite content).
    Repack(Vec<String>),
    /// Text generated by the installer.
    Generated(Vec<u8>),
    /// A `.lif` with a level number changed.
    LifRenumber { entry: String, from: u32, to: u32 },
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Action {
    Create,
    /// The destination exists and will be replaced (only with [`Conflict::Overwrite`]).
    Overwrite,
    Skip,
}

#[derive(Clone, Debug)]
pub struct PlanItem {
    /// Destination relative to the install root, `/` separated.
    pub dest: String,
    pub source: Source,
    pub size: u64,
    pub action: Action,
    pub note: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LoadOrderEntry {
    pub stage: String,
    pub name: String,
    /// Already listed (possibly disabled with `;`): left alone.
    pub already_listed: bool,
}

#[derive(Clone, Debug)]
pub struct Renumber {
    pub dir: String,
    pub from: u32,
    pub to: u32,
}

#[derive(Clone, Debug)]
pub struct InstallPlan {
    pub archive: PathBuf,
    pub name: String,
    pub kind: Kind,
    pub item: Option<ItemRef>,
    pub items: Vec<PlanItem>,
    pub load_order: Vec<LoadOrderEntry>,
    /// `mods/load_order.cfg` does not exist yet.
    pub creates_load_order: bool,
    pub renumbered: Vec<Renumber>,
    /// Levels the plan installs: (folder, number, display name).
    pub levels: Vec<(String, u32, String)>,
    pub campaigns: Vec<String>,
    pub warnings: Vec<String>,
    /// Reasons the plan cannot be applied.
    pub blocked: Vec<String>,
    pub archive_sha256: String,
    /// Wrapper folder (with trailing `/`) stripped from the archive paths in `Source::Repack`.
    pub strip_prefix: String,
}

impl InstallPlan {
    pub fn is_blocked(&self) -> bool {
        !self.blocked.is_empty()
    }
    pub fn applied_items(&self) -> impl Iterator<Item = &PlanItem> {
        self.items.iter().filter(|i| i.action != Action::Skip)
    }
    pub fn count(&self, a: Action) -> usize {
        self.items.iter().filter(|i| i.action == a).count()
    }
    pub fn total_size(&self) -> u64 {
        self.applied_items().map(|i| i.size).sum()
    }
    /// Human-readable plan lines (what the confirmation dialog shows).
    pub fn describe(&self) -> Vec<String> {
        let mut out = vec![format!(
            "{}: {} ({} files, {})",
            self.kind.label(),
            self.name,
            self.applied_items().count(),
            crate::util::format_size(self.total_size())
        )];
        let mut dirs: BTreeMap<String, (usize, usize, usize)> = BTreeMap::new();
        for i in &self.items {
            let d = i
                .dest
                .rsplit_once('/')
                .map(|x| x.0)
                .unwrap_or("")
                .to_string();
            let e = dirs.entry(d).or_default();
            match i.action {
                Action::Create => e.0 += 1,
                Action::Overwrite => e.1 += 1,
                Action::Skip => e.2 += 1,
            }
        }
        for (d, (c, o, s)) in dirs {
            let mut t = format!("  {}/: {c} new", if d.is_empty() { "." } else { &d });
            if o > 0 {
                t.push_str(&format!(", {o} OVERWRITTEN"));
            }
            if s > 0 {
                t.push_str(&format!(", {s} skipped (already there)"));
            }
            out.push(t);
        }
        for r in &self.renumbered {
            out.push(format!(
                "  level {} in {} renumbered to {}",
                r.from, r.dir, r.to
            ));
        }
        for e in &self.load_order {
            out.push(if e.already_listed {
                format!(
                    "  mods/load_order.cfg: {} already listed in [{}]",
                    e.name, e.stage
                )
            } else {
                format!("  mods/load_order.cfg: add {} to [{}]", e.name, e.stage)
            });
        }
        out.extend(self.warnings.iter().map(|w| format!("  warning: {w}")));
        out.extend(self.blocked.iter().map(|w| format!("  BLOCKED: {w}")));
        out
    }
}

// ---------------------------------------------------------------- helpers

fn child_ci(dir: &Path, name: &str) -> Option<String> {
    if std::fs::symlink_metadata(dir.join(name)).is_ok() {
        return Some(name.to_string());
    }
    let lower = name.to_ascii_lowercase();
    std::fs::read_dir(dir)
        .ok()?
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .find(|n| n.to_ascii_lowercase() == lower)
}

/// Resolve `rel` against the existing folder names ignoring case. Returns the path with the
/// existing spelling for the part that exists, and whether the whole path exists.
pub fn resolve_ci(root: &Path, rel: &str) -> (String, bool) {
    let mut cur = root.to_path_buf();
    let mut out: Vec<String> = vec![];
    let mut exists = true;
    for comp in rel.split('/') {
        if exists {
            if let Some(n) = child_ci(&cur, comp) {
                cur.push(&n);
                out.push(n);
                continue;
            }
            exists = false;
        }
        out.push(comp.to_string());
    }
    (out.join("/"), exists)
}

fn level_files_in(dir: &Path) -> BTreeSet<u32> {
    let mut s = BTreeSet::new();
    for e in std::fs::read_dir(dir).into_iter().flatten().flatten() {
        if let Some(n) = crate::classify::level_number(&e.file_name().to_string_lossy()) {
            s.insert(n);
        }
    }
    s
}

fn renumber_name(name: &str, to: u32) -> String {
    // `mapNNNNN.rest` -> `map<to>.rest`
    format!("map{to:05}{}", &name[8..])
}

fn split_dir(p: &str) -> (&str, &str) {
    match p.rfind('/') {
        Some(i) => (&p[..i], &p[i + 1..]),
        None => ("", p),
    }
}

/// Default destination pack for loose levels: `personal` (the pack meant for user levels), else
/// `standard`, else a new pack named after the item.
pub fn default_pack_target(install: &Path, class_kind: Kind, name: &str) -> PackTarget {
    if class_kind == Kind::MapPack {
        return PackTarget::New(slug(name));
    }
    for p in ["personal", "standard"] {
        if resolve_ci(install, &format!("levels/{p}.cfg")).1 {
            return PackTarget::Existing(p.to_string());
        }
    }
    PackTarget::New(slug(name))
}

/// Existing level pack folders (`levels/*.cfg` with a `LEVELS_LOCATION`), by folder name.
pub fn existing_packs(install: &Path) -> Vec<String> {
    let mut v = vec![];
    let dir = resolve_ci(install, "levels").0;
    for e in std::fs::read_dir(install.join(dir))
        .into_iter()
        .flatten()
        .flatten()
    {
        let n = e.file_name().to_string_lossy().into_owned();
        if let Some(stem) = n.strip_suffix(".cfg").or_else(|| n.strip_suffix(".CFG")) {
            if let Ok(b) = std::fs::read(e.path()) {
                let t = kfx_formats::cfg::latin1_decode(&b).to_ascii_uppercase();
                if t.contains("LEVELS_LOCATION") {
                    v.push(stem.to_string());
                }
            }
        }
    }
    v.sort();
    v
}

fn mod_cfg_value(text: &str, key: &str) -> Option<String> {
    for l in text.lines() {
        let l = l.trim();
        if let Some((k, v)) = l.split_once('=') {
            if k.trim().eq_ignore_ascii_case(key) {
                return Some(v.trim().to_string());
            }
        }
    }
    None
}

