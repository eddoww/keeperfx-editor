impl ArgKind {
    /// Kind implied by a plain type letter.
    pub fn from_letter(c: u8) -> ArgKind {
        match c.to_ascii_uppercase() {
            b'N' => ArgKind::Number,
            b'C' => ArgKind::Creature,
            b'P' => ArgKind::Player,
            b'R' => ArgKind::Room,
            b'S' => ArgKind::Slab,
            b'L' => ArgKind::Location,
            b'O' => ArgKind::Operator,
            b'B' => ArgKind::Bool,
            _ => ArgKind::Text,
        }
    }
    /// Kinds that stand for a map coordinate the map view can pick.
    pub fn is_coordinate(self) -> bool {
        matches!(
            self,
            ArgKind::SubtileX | ArgKind::SubtileY | ArgKind::SlabX | ArgKind::SlabY
        )
    }
}

#[derive(Debug, Deserialize)]
struct RawCmd {
    doc: String,
    args: Vec<String>,
    #[serde(default)]
    auto: bool,
}
#[derive(Debug, Deserialize)]
struct RawOverlay {
    lists: HashMap<String, Vec<String>>,
    commands: HashMap<String, RawCmd>,
    #[serde(default)]
    removed: HashMap<String, RawCmd>,
}

/// One annotated argument.
#[derive(Clone, Debug)]
pub struct OverlayArg {
    pub name: String,
    pub kind: ArgKind,
    /// The display name was guessed (the C code does not name it).
    pub guessed: bool,
}

#[derive(Clone, Debug)]
pub struct CmdInfo {
    pub doc: String,
    pub args: Vec<OverlayArg>,
    /// Generated by `tools/sync_keeperfx.py` from the type letters of a command that is new or
    /// changed upstream: the names are generic and no description was written yet.
    pub auto: bool,
}

#[derive(Debug)]
pub struct Overlay {
    pub commands: HashMap<String, CmdInfo>,
    pub lists: HashMap<String, Vec<String>>,
    /// Entries of commands that KeeperFX removed from its command table.
    pub removed: HashMap<String, CmdInfo>,
}

static OVERLAY: OnceLock<Overlay> = OnceLock::new();

/// Description shown for a command whose overlay entry was generated (`"auto": true`) and has no
/// description yet.
pub const AUTO_DOC: &str = "A command newer than the editor's notes on its arguments: the \
    argument names are generic, derived from the argument types of the command table.";

fn cmd_info(v: RawCmd) -> Result<CmdInfo, String> {
    let args = v
        .args
        .iter()
        .map(|a| {
            let (n, kind) = a
                .split_once(':')
                .ok_or_else(|| format!("argument {a:?} is not name:kind"))?;
            let (n, guessed) = match n.strip_suffix('*') {
                Some(x) => (x, true),
                None => (n, false),
            };
            Ok(OverlayArg {
                name: n.to_string(),
                kind: ArgKind::from_name(kind).ok_or_else(|| format!("unknown kind {kind:?}"))?,
                guessed,
            })
        })
        .collect::<Result<_, String>>()?;
    Ok(CmdInfo {
        doc: v.doc,
        args,
        auto: v.auto,
    })
}

fn cmd_map(raw: HashMap<String, RawCmd>) -> Result<HashMap<String, CmdInfo>, String> {
    raw.into_iter()
        .map(|(k, v)| {
            cmd_info(v)
                .map(|c| (k.clone(), c))
                .map_err(|e| format!("{k}: {e}"))
        })
        .collect()
}

impl Overlay {
    /// The overlay embedded in this build (or the one given to [`Overlay::install`]).
    pub fn get() -> &'static Overlay {
        OVERLAY.get_or_init(|| {
            Overlay::from_json(OVERLAY_JSON).expect("embedded script_arg_overlay.json")
        })
    }

    /// Parse an overlay in the format of `data/script_arg_overlay.json`.
    pub fn from_json(json: &str) -> Result<Overlay, String> {
        let raw: RawOverlay = serde_json::from_str(json).map_err(|e| e.to_string())?;
        Ok(Overlay {
            commands: cmd_map(raw.commands)?,
            lists: raw.lists,
            removed: cmd_map(raw.removed)?,
        })
    }

    /// Use `overlay` instead of the embedded data for the rest of the process. Only possible
    /// before the first [`Overlay::get`]; gives the overlay back otherwise (see
    /// [`crate::Tables::install`]).
    pub fn install(overlay: Overlay) -> Result<(), Overlay> {
        OVERLAY.set(overlay)
    }

    /// Description of `cmd` for signature help: the written one, or for a generated entry a
    /// note that the argument names are generic.
    pub fn doc(&self, cmd: &str) -> String {
        match self.commands.get(cmd) {
            Some(c) if c.doc.is_empty() && c.auto => AUTO_DOC.to_string(),
            Some(c) => c.doc.clone(),
            None => String::new(),
        }
    }

    /// Entry of a command KeeperFX removed (and the editor's table no longer has).
    pub fn removed(&self, name: &str) -> Option<&CmdInfo> {
        self.removed.get(name)
    }

    pub fn cmd(&self, name: &str) -> Option<&CmdInfo> {
        self.commands.get(name)
    }

    pub fn list(&self, name: &str) -> &[String] {
        self.lists.get(name).map(|v| v.as_slice()).unwrap_or(&[])
    }

    /// Annotation of argument `slot` of `cmd`. Repeating commands reuse their last annotation.
    pub fn arg(&self, cmd: &str, slot: usize) -> Option<&OverlayArg> {
        let info = self.commands.get(cmd)?;
        info.args.get(slot).or_else(|| {
            let repeats = crate::tables::Tables::get()
                .find_full(cmd)
                .map(|d| d.repeats())
                .unwrap_or(false);
            if repeats {
                info.args.last()
            } else {
                None
            }
        })
    }
}
