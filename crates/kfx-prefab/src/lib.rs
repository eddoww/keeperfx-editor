//! kfx-prefab: prefabs (stamps) for the KeeperFX map editor, the level text translation
//! workflow and the groundwork for localising the editor itself.
//!
//! * Part A, prefabs: [`model`] (the `*.kfxprefab` file format), [`capture`] (document ->
//!   prefab), [`apply`] (prefab -> document as one undoable `Patch`, name resolution, renumbering,
//!   ghost preview), [`transform`] (rotation / flip of a prefab), [`script`] (script fragment
//!   placeholders), [`clip`] (conversion to / from the editor's clipboard shape), [`library`]
//!   (folders of prefab files), [`render`] (top-down colour renderer) and [`ui`] (the egui
//!   library browser), [`starter`] (the shipped starter set, authored with [`capture`]).
//! * Part B, [`texts`]: collect the string ids a level uses, translate them in a grid, CSV / `.po`
//!   exchange, outdated tracking.
//! * Part C, [`i18n`]: the editor's own texts, `trd("key", "English")` and friends with the
//!   English in the code, the catalogue format and the source scanner ([`i18n::scan`]); the
//!   example `extract_strings` writes `data/i18n/en.toml` from the code.
