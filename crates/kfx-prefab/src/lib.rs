/// Errors of this crate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// Malformed or inconsistent input.
    Invalid(String),
    /// The document or target cannot take the operation.
    Refused(String),
    /// File access failed.
    Io(String),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Invalid(s) | Error::Refused(s) | Error::Io(s) => f.write_str(s),
        }
    }
}
impl std::error::Error for Error {}

impl From<kfx_formats::Error> for Error {
    fn from(e: kfx_formats::Error) -> Error {
        Error::Io(e.to_string())
    }
}
impl From<kfx_map::Error> for Error {
    fn from(e: kfx_map::Error) -> Error {
        Error::Invalid(e.to_string())
    }
}

pub type Result<T> = std::result::Result<T, Error>;
