//! Writes the starter prefab set and (for the default folder) the list that embeds it.
//! Usage: `make_starter [OUT_DIR]` (default `data/prefabs` of the workspace); the game
//! configuration comes from the test install (`KFX_INSTALL`).
use kfx_map::gamedata::{ConfigLayers, GameData};

fn main() {
    let default = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/prefabs");
    let custom = std::env::args().nth(1).map(std::path::PathBuf::from);
    let out = custom.clone().unwrap_or_else(|| default.clone());
    let install = kfx_formats::testutil::install_dir().expect("a KeeperFX install (KFX_INSTALL)");
    let gd = GameData::load(&ConfigLayers::for_level(&install, None, None, None, None))
        .expect("game data");
    std::fs::create_dir_all(&out).expect("output folder");
    let files = kfx_prefab::starter::write_all(&gd, &out).unwrap_or_else(|e| panic!("{e}"));
    for f in &files {
        println!("wrote {}", out.join(f).display());
    }
    println!("{} prefabs", files.len());
    if custom.is_none() {
        let mut list = String::from(
            "//! The starter set embedded in the library (generated by \
                the example `make_starter`).\npub const STARTER_FILES: &[(&str, &str)] = &[\n",
        );
        for f in &files {
            list.push_str(&format!(
                "    (\"{f}\", include_str!(\"../../../data/prefabs/{f}\")),\n"
            ));
        }
        list.push_str("];\n");
        let p = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/starter_files.rs");
        std::fs::write(&p, list).expect("write starter_files.rs");
        println!("wrote {}", p.display());
    }
}
