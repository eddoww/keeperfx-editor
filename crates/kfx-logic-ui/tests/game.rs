//! Semantic check through the real game: a script built with the model (a timer-triggered
//! party spawn and a flag chain) runs on keeporig map 1 while a level Lua script prints the
//! flags and the hero creatures every 20 turns. Needs `KFX_GAME_TEST=1` and the test install;
//! uses the offscreen harness of `crates/kfx-map/tests/support/game.rs` (one game at a time,
//! hard timeout, the process is always killed).
#![cfg(unix)]
#[path = "../../kfx-map/tests/support/game.rs"]
mod game;

use game::Rig;
use kfx_formats::level_bin::{self, MapDims};
use kfx_formats::{rnc, testutil};
use kfx_logic_ui::*;

const SECS: u64 = 30;

/// Prints `KFXLOGIC <turn> <FLAG1> <FLAG2> <FLAG3> <TIMER0> <knights> <archers>` every 20 turns
/// (hero creatures = owner PLAYER_GOOD, player id 4).
const PROBE: &str = r#"
function KfxLogicProbe()
  local knights, archers = 0, 0
  for _, t in ipairs(GetThingsOfClass("Creature")) do
    if t.owner.playerId == 4 then
      if tostring(t.model) == "KNIGHT" then knights = knights + 1 end
      if tostring(t.model) == "ARCHER" then archers = archers + 1 end
    end
  end
  print("KFXLOGIC " .. PLAYER0.GAME_TURN .. " " .. PLAYER0.FLAG1 .. " " .. PLAYER0.FLAG2 .. " " .. PLAYER0.FLAG3 .. " " .. PLAYER0.TIMER0 .. " " .. knights .. " " .. archers)
end
RegisterTimerEvent(KfxLogicProbe, 20, true)
"#;

/// The level's own script with the generated logic appended.
fn build_script(original: &[u8]) -> String {
    let mut doc = import(original);
    assert!(doc.read_only.is_none(), "{:?}", doc.read_only);
    let mut p = doc.new_party("KFXRAID");
    p.pre = vec![
        String::new(),
        "REM generated by the kfx-logic-ui game test".into(),
    ];
    let m1 = doc.new_member("KNIGHT", 2, 0, "DEFEND_PARTY", 0);
    let m2 = doc.new_member("KNIGHT", 2, 0, "DEFEND_PARTY", 0);
    p.members = vec![m1, m2];
    doc.nodes.push(Node::Party(p));
    // 1. at turn 100: spawn the party at the player's heart and set FLAG1
    let c = doc.new_condition(Cmd::new("IF", &["PLAYER0", "GAME_TURN", ">=", "100"]));
    let a1 = doc.new_action(Cmd::new(
        "ADD_PARTY_TO_LEVEL",
        &["PLAYER_GOOD", "KFXRAID", "PLAYER0", "1"],
    ));
    let a2 = doc.new_action(Cmd::new("SET_FLAG", &["PLAYER0", "FLAG1", "1"]));
    let e1 = doc.new_event(vec![c], vec![Node::Action(a1), Node::Action(a2)]);
    let e1_id = e1.id;
    doc.nodes.push(Node::Event(e1));
    // 2. chained on FLAG1: FLAG2 = 5 and start TIMER0
    let c = doc.new_condition(Cmd::new("IF", &["PLAYER0", "FLAG1", "==", "1"]));
    let a1 = doc.new_action(Cmd::new("SET_FLAG", &["PLAYER0", "FLAG2", "5"]));
    let a2 = doc.new_action(Cmd::new("SET_TIMER", &["PLAYER0", "TIMER0"]));
    let e2 = doc.new_event(vec![c], vec![Node::Action(a1), Node::Action(a2)]);
    doc.nodes.push(Node::Event(e2));
    // 3. TIMER0 >= 200: two archers and FLAG3 = 7
    let c = doc.new_condition(Cmd::new("IF", &["PLAYER0", "TIMER0", ">=", "200"]));
    let a1 = doc.new_action(Cmd::new(
        "ADD_CREATURE_TO_LEVEL",
        &["PLAYER_GOOD", "ARCHER", "PLAYER0", "2", "1", "0"],
    ));
    let a2 = doc.new_action(Cmd::new("SET_FLAG", &["PLAYER0", "FLAG3", "7"]));
    let e3 = doc.new_event(vec![c], vec![Node::Action(a1), Node::Action(a2)]);
    doc.nodes.push(Node::Event(e3));
    let _ = e1_id;
    let text = export(&doc);
    // what the editor reads back from it: the timeline knows when each event fires
    let back = import(text.as_bytes());
    let t = analysis::earliest_turns(&back);
    let evs: Vec<&Event> = back
        .events()
        .into_iter()
        .map(|(e, _)| e)
        .filter(|e| !e.conditions.is_empty())
        .collect();
    let n = evs.len();
    assert_eq!(t.get(&evs[n - 3].id), Some(&100));
    assert_eq!(
        t.get(&evs[n - 1].id),
        None,
        "FLAG1 chain start is not time-derivable"
    );
    text
}

#[test]
fn generated_logic_runs_in_game() {
    if std::env::var("KFX_GAME_TEST").ok().as_deref() != Some("1") {
        println!("KFX_GAME_TEST != 1: skipped");
        return;
    }
    let Some(inst) = testutil::install_dir() else {
        return;
    };
    let src = testutil::resolve_ci(&inst, "campgns/keeporig").unwrap();
    let slb = rnc::load_file(&level_bin::find_file(&src, 1, "slb").unwrap()).unwrap();
    let dims = MapDims::from_slb_len(slb.len()).unwrap();
    let original = rnc::load_file(&level_bin::find_file(&src, 1, "txt").unwrap()).unwrap();
    let script = build_script(&original);
    let rep = kfx_script::validate(
        &kfx_script::Document::parse(script.as_bytes()),
        &kfx_script::InstallProvider::new(&inst),
    );
    let errs: Vec<_> = rep
        .diagnostics
        .iter()
        .filter(|d| d.severity == kfx_script::Severity::Error)
        .collect();
    assert!(errs.is_empty(), "{errs:?}");
    let rig = Rig::new(&inst, "kfx-logic-ui");
    rig.install_level(1, &src, 1, dims.w as u16, dims.h as u16, Some(&script));
    rig.write_level_file(1, "lua", PROBE);
    let run = rig.run(1, SECS);
    println!("{}", run.summary());
    let rows: Vec<Vec<i64>> = run
        .lines
        .iter()
        .filter_map(|l| {
            l.raw.find("KFXLOGIC ").map(|i| {
                l.raw[i + 9..]
                    .split_whitespace()
                    .filter_map(|v| v.parse().ok())
                    .collect::<Vec<i64>>()
            })
        })
        .filter(|v| v.len() == 7)
        .collect();
    for r in &rows {
        println!(
            "turn {:5}  FLAG1 {} FLAG2 {} FLAG3 {} TIMER0 {:5}  knights {} archers {}",
            r[0], r[1], r[2], r[3], r[4], r[5], r[6]
        );
    }
    for l in run.problems().iter().take(20) {
        println!("  log: {}", l.raw);
    }
    let _ = std::fs::remove_dir_all(&rig.dir);
    assert!(run.started, "level did not start");
    assert!(!run.crashed, "game crashed");
    assert!(!rows.is_empty(), "no probe output");
    let last = rows.last().unwrap();
    assert!(last[0] >= 360, "the run reached only turn {}", last[0]);
    for r in &rows {
        let turn = r[0];
        // nothing before turn 100; the party (2 knights) and FLAG1/FLAG2 from turn 100 on
        if turn < 100 {
            assert_eq!((r[1], r[2], r[5]), (0, 0, 0), "turn {turn}: too early");
        }
        if turn >= 120 {
            assert_eq!((r[1], r[2]), (1, 5), "turn {turn}: flag chain");
            assert_eq!(r[5], 2, "turn {turn}: the party of 2 knights");
        }
        // TIMER0 starts one turn after FLAG1 is set (the next condition pass); archers 200 later
        if turn < 300 {
            assert_eq!((r[3], r[6]), (0, 0), "turn {turn}: archers too early");
        }
        if turn >= 340 {
            assert_eq!((r[3], r[6]), (7, 2), "turn {turn}: timer-triggered spawn");
        }
    }
}
