def walk_enums(obj, used):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in ("enum", "names_enum") and isinstance(v, str):
                used.add(v)
            elif k == "enum_by_arg0" and isinstance(v, dict):
                used.update(v.values())
            else:
                walk_enums(v, used)
    elif isinstance(obj, list):
        for v in obj:
            walk_enums(v, used)


def finalize_key(k, doc_sources, cnt):
    fdoc = k.pop("_fxdoc", None)
    wdoc = k.pop("_wikidoc", None)
    cdoc = k.pop("_cdoc", None)
    parts = [p for p in (fdoc, wdoc, cdoc) if p]
    if fdoc and wdoc:
        src = "both"
    elif fdoc:
        src = "fxdata"
    elif wdoc:
        src = "wiki"
    else:
        src = None
    out = OrderedDict()
    for f in ("name", "whole_line", "repeat"):
        out[f] = k[f]
    for f in ("ignored", "wildcard", "table", "array", "array_len", "tuple"):
        if f in k:
            out[f] = k[f]
    out["args"] = k["args"]
    if "fields" in k:
        nested = Counter()
        out["fields"] = [finalize_key(x, Counter(), nested) for x in k["fields"]]
        cnt["unknown"] += nested["unknown"]  # unknown nested fields count as keys of their own
    out["parse"] = k.get("parse")
    out["assign"] = k.get("assign")
    out["source"] = k.get("source")
    out["doc"] = "\n".join(parts) if parts else None
    out["doc_source"] = src
    out["confidence"] = k["confidence"]
    cnt[k["confidence"]] += 1
    if src:
        doc_sources[src] += 1
    if parts:
        doc_sources["with_doc"] += 1
    return out


def c_string_index(src_root):
    """Map lower-cased string literals of the C sources to their first location."""
    idx = {}
    for p in sorted((src_root / "src").rglob("*")):
        if p.suffix not in (".c", ".h", ".cpp") or not p.is_file():
            continue
        rel = p.relative_to(src_root).as_posix()
        raw = read_text(p)
        for m in re.finditer(r"\"([A-Za-z_][\w]{2,})\"", raw):
            idx.setdefault(m.group(1).lower(), "%s:%d" % (rel, raw.count("\n", 0, m.start()) + 1))
    return idx


def unknown_note(name, cstrings, toml):
    if toml:
        return ("Present in the shipped files but the TOML loader never looks this key up "
                "(ignored by the game); type guessed from values.")
    loc = cstrings.get(name.lower())
    if loc:
        return ("Present in the shipped files; the name also appears in the C source at %s, but the "
                "extractor could not attribute it to this block; type guessed from values." % loc)
    return ("Present in the shipped files but the name does not appear anywhere in the C source tree, so this "
            "version of the game ignores it (likely added or removed in another version); type guessed from values.")


def harvest_shipped(files_out, install, cstrings):
    for e in files_out:
        e["_cstrings"] = cstrings
        where = e.get("_where")
        if e["file"] == "creatrs/*.cfg":
            paths = sorted((install / "creatrs").glob("*.cfg"))
        else:
            p = install / where / e["file"]
            paths = [p] if p.is_file() else []
        recs = []
        sdocs = {}
        for p in paths:
            text = read_text(p)
            if e["format"] == "cfg":
                ks, sd = parse_cfg_doc(text)
            else:
                ks, sd = parse_toml_doc(text)
            recs.extend(ks)
            for s, d in sd.items():
                sdocs.setdefault(s, []).extend(d)
        if not paths:
            e["_shipped"] = False
            continue
        e["_shipped"] = True
        if e["format"] == "cfg":
            merge_cfg(e, recs, sdocs)
        else:
            merge_toml(e, recs, sdocs)
        e.pop("_shipped", None)


def section_for(e, name):
    """Find the schema section a shipped section name belongs to."""
    for s in e["sections"]:
        if not s["numbered"] and s["name"].lower() == name.lower():
            return s, None
    base, num = split_numbered(name)
    if num is not None:
        for s in e["sections"]:
            if s["numbered"] and s["name"].lower() == base.lower():
                return s, num
    return None, num


def merge_cfg(e, recs, sdocs):
    known = {}
    unknown_secs = OrderedDict()
    extra_keys = {}
    for (secname, key, val, doc, ln) in recs:
        s, num = section_for(e, secname)
        if s is not None and s.get("wildcard_keys"):
            continue
        if s is None:
            base, num = split_numbered(secname)
            nm = base if num is not None else secname
            if nm not in unknown_secs:
                unknown_secs[nm] = OrderedDict([("name", nm), ("numbered", num is not None), ("source", None),
                                                ("list", None), ("keys", []), ("confidence", "unknown")])
            s = unknown_secs[nm]
        kk = None
        for k in s["keys"]:
            if k["name"].upper() == key.upper():
                kk = k
                break
        if kk is None:
            kk = extra_keys.setdefault((id(s), key.upper()), OrderedDict([
                ("name", key), ("whole_line", False), ("repeat", False), ("args", None),
                ("parse", None), ("assign", None), ("source", None), ("confidence", "unknown"),
                ("_vals", []), ("_docs", []), ("_sec", s)]))
            kk["_vals"].append(val)
            kk["_docs"].append(doc)
            continue
        known.setdefault(id(kk), (kk, []))[1].append(doc)
    for kid, (k, docs) in known.items():
        d = best_doc(docs)
        if d:
            k["_fxdoc"] = d
    for (sid, kname), k in sorted(extra_keys.items(), key=lambda x: (x[0][0], x[0][1])):
        s = k.pop("_sec")
        k["args"] = guess_cfg_args(k.pop("_vals"))
        d = best_doc(k.pop("_docs"))
        if d:
            k["_fxdoc"] = d
        k["_cdoc"] = unknown_note(k["name"], e["_cstrings"], False)
        s.setdefault("_unknown", []).append(k)
    for s in list(e["sections"]) + list(unknown_secs.values()):
        unk = s.pop("_unknown", [])
        unk.sort(key=lambda k: k["name"].upper())
        s["keys"].extend(unk)
    for us in unknown_secs.values():
        us["doc"] = "Block found in the shipped files but not read by the loaders the extractor knows about."
        e["sections"].append(us)
    # section docs
    for s in e["sections"]:
        docs = []
        for secname, ds in sdocs.items():
            ss, num = section_for(e, secname)
            if ss is s:
                docs.extend(ds)
        d = section_doc(s, docs)
        if d:
            s["_doc"] = d


def merge_toml(e, recs, sdocs):
    def find_key(keys, name):
        for k in keys:
            if k["name"] == name or k["name"].upper() == name.upper():
                return k
        return None

    extras = {}
    for (secname, key, val, doc, ln) in recs:
        if secname is None:
            path = [""]
        else:
            path = secname.split(".")
        s, num = section_for(e, path[0])
        if s is None:
            continue
        keys = s["keys"]
        container = s
        for sub in path[1:]:
            k = find_key(keys, sub)
            if k is None:
                keys = None
                break
            container = k
            keys = k.setdefault("fields", [])
        if keys is None:
            continue
        k = find_key(keys, key)
        if k is None:
            ex = extras.setdefault((id(container), key), {"container": container, "name": key, "vals": [], "docs": []})
            ex["vals"].append(val)
            ex["docs"].append(doc)
            continue
        k.setdefault("_docs", []).append(doc)
    for (cid, name), ex in sorted(extras.items(), key=lambda x: (x[0][0], x[0][1])):
        args, extra = guess_toml_args(ex["vals"])
        k = mk_key(name, args, None, "unknown", unknown_note(name, e["_cstrings"], True), **extra)
        d = best_doc(ex["docs"])
        if d:
            k["_fxdoc"] = d
        cont = ex["container"]
        cont.setdefault("_unknown", []).append(k)

    def fin(keys):
        for k in keys:
            ds = k.pop("_docs", None)
            if ds:
                d = best_doc(ds)
                if d:
                    k["_fxdoc"] = d
            if "fields" in k:
                fin(k["fields"])
                unk = k.pop("_unknown", [])
                k["fields"].extend(sorted(unk, key=lambda x: x["name"].upper()))

    for s in e["sections"]:
        fin(s["keys"])
        unk = s.pop("_unknown", [])
        s["keys"].extend(sorted(unk, key=lambda x: x["name"].upper()))
        docs = []
        for secname, ds in sdocs.items():
            ss, num = section_for(e, secname.split(".")[0])
            if ss is s and "." not in secname:
                docs.extend(ds)
        d = section_doc(s, docs)
        if d:
            s["_doc"] = d


def section_doc(s, docs):
    """Comment above a block header. For numbered blocks the comment usually describes one
    item, so only a comment repeated above several blocks is kept."""
    docs = [d for d in docs if d and d.strip()]
    if not docs:
        return None
    if s.get("numbered"):
        c = Counter(docs)
        rep = [d for d in docs if c[d] >= 2]
        return rep[0] if rep else None
    return best_doc(docs)


