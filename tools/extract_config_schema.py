#!/usr/bin/env python3
"""Extract a JSON schema of the KeeperFX config files from the C config loaders.

Regenerate (from the repository root):

    python3 -I tools/extract_config_schema.py \
        --src "$KFX_SOURCE" --install "$KFX_INSTALL" --wiki "$KFX_WIKI" \
        --out data/config_schema.json

--src is a checkout of the KeeperFX C repository, --install a KeeperFX install (its shipped
config files are read for comments and extra keys), --wiki the folder of a checkout of
https://github.com/dkfans/keeperfx.wiki that holds the Markdown pages. Each defaults to the
environment variable shown; the script stops with a message when one is missing. --out defaults
to data/config_schema.json of this repository. Standard library only. The inputs are only read;
the only file written is --out. Output is deterministic.

Sources of information, from most to least trusted:
  * NamedField tables (name, argnum, default, min, max, NamedCommand, parse and
    assign functions) and NamedFieldSet block descriptions -> confidence "full".
  * CONDITIONAL_ASSIGN_* macro calls in the TOML loaders -> "full".
  * switch (cmd_num) parsers fed by recognize_conf_command(); each case body is
    read heuristically (get_conf_parameter_single calls, the lookups that follow
    them, loops) -> "partial".
  * keys only found in the shipped config files -> "unknown".
Docs come from the comment lines above keys/sections in the shipped files and
from the KeeperFX wiki.
"""

