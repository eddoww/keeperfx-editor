def synthetic_token_enum(cf, func, enums):
    """Collect strcasecmp(token, "X") literals of a custom parse function."""
    f = cf.function(func)
    if not f:
        return None
    body = cf.text[f[1]:f[2]]
    toks = re.findall(r"str(?:case)?cmp\s*\(\s*\w+\s*,\s*\"([^\"]+)\"\s*\)", body)
    if not toks:
        return None
    name = "%s:tokens" % func
    enums[name] = [{"name": t, "value": None} for t in toks]
    return name


