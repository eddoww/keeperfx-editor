class NamedTables:
    def __init__(self, src_root, consts):
        self.tables = {}   # name -> dict(entries=[(name, expr, value)], loc, long)
        self.dynamic = {}  # name -> loc
        rx = re.compile(r"(?:static\s+)?(?:const\s+)?struct\s+(Long)?NamedCommand\s+(\w+)\s*\[([^\]]*)\]\s*(=\s*\{|;)")
        entry_rx = re.compile(r"\{\s*(\"(?:[^\"\\]|\\.)*\"|NULL|0)\s*,?\s*([^{}]*?)\s*\}")
        files = sorted(p.relative_to(src_root).as_posix() for p in (src_root / "src").rglob("*")
                       if p.suffix in (".c", ".h") and p.is_file())
        for rel in files:
            cf = CFile(src_root, rel)
            for m in rx.finditer(cf.text):
                name = m.group(2)
                if m.group(4) == ";":
                    if rel.endswith(".c"):
                        self.dynamic.setdefault(name, cf.loc(m.start()))
                    continue
                start = m.end() - 1
                end = match_bracket(cf.text, start)
                body = cf.text[start + 1:end]
                entries = []
                for em in entry_rx.finditer(body):
                    nm = em.group(1)
                    if nm in ("NULL", "0"):
                        break
                    nm = nm[1:-1]
                    expr = " ".join(em.group(2).split()).rstrip(",").strip()
                    entries.append((nm, expr, consts.eval(expr)))
                if name in self.tables:
                    continue
                self.tables[name] = {"entries": entries, "loc": cf.loc(m.start()), "long": bool(m.group(1))}

    def get(self, name):
        return self.tables.get(name)


