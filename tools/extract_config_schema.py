def arg_from_table(name, consts, tables_used):
    """Build an enum arg description from a NamedCommand table name."""
    a = {"type": "enum", "enum": name}
    ref = REF_BY_TABLE.get(name)
    if ref:
        a["ref"] = ref
    tables_used.add(name)
    return a


def namedfield_key(rows, consts, named, tables_used, cf, synth_enums):
    rows = sorted(rows, key=lambda r: int(r["argnum"]) if re.match(r"^-?\d+$", r["argnum"]) else 0)
    first = rows[0]
    key = OrderedDict()
    key["name"] = first["name"]
    key["whole_line"] = any(r["argnum"].strip() == "-1" for r in rows)
    key["repeat"] = False
    args = []
    confidences = []
    docs = []
    for r in rows:
        pf = r["parse"]
        info = PARSE_FUNCS.get(pf)
        a = OrderedDict()
        if info is None:
            a["type"] = "unknown"
            confidences.append("partial")
            docs.append("Parsed by %s (not interpreted by the extractor)." % pf)
            clamps = False
        else:
            typ, clamps, conf, doc = info
            a["type"] = typ
            confidences.append(conf)
            if doc and doc not in docs:
                docs.append(doc)
        nc = re.sub(r"^\(\s*(?:const\s+)?struct\s+\w+\s*\*\s*\)\s*", "", r["named"])
        nc = nc if nc not in ("NULL", "0") else None
        if pf == "value_default" and nc:
            a["type"] = "enum"
        if pf in PARSE_FUNC_ENUM:
            nc = PARSE_FUNC_ENUM[pf]
        if pf == "value_overrides":
            se = synthetic_token_enum(cf, pf, synth_enums)
            if se:
                a["enum"] = se
        if nc and a["type"] in ("enum", "flags", "longflags", "function", "name"):
            if a["type"] != "name":
                a["enum"] = nc
                tables_used.add(nc)
            ref = REF_BY_TABLE.get(nc)
            if ref and a["type"] in ("enum",):
                a["ref"] = ref
        if pf in PARSE_FUNC_REF:
            a["ref"] = PARSE_FUNC_REF[pf]
        if clamps:
            number_with_symbol(consts, r["min"], "min", "min_symbol", a)
            number_with_symbol(consts, r["max"], "max", "max_symbol", a)
        dflt = " ".join(r["default"].split())
        dv = consts.eval(dflt) if a["type"] not in ("name", "string") else None
        if dv is not None:
            a["default"] = dv
            if not is_plain_number(dflt):
                a["default_symbol"] = dflt
        elif dflt not in ("0", "NULL") and a["type"] not in ("name", "string"):
            a["default_symbol"] = dflt
        if r["member"]:
            a["label"] = re.split(r"[\.>]", r["member"])[-1].replace("-", "")
        if r["parse"] != first["parse"]:
            a["parse"] = r["parse"]
        if r["assign"] != first["assign"]:
            a["assign"] = r["assign"]
        args.append(a)
    key["args"] = args
    key["parse"] = first["parse"]
    key["assign"] = first["assign"]
    key["source"] = first["loc"]
    if docs:
        key["_cdoc"] = " ".join(docs)
    key["confidence"] = "partial" if "partial" in confidences else "full"
    return key


def group_rows(rows):
    order = []
    groups = {}
    for r in rows:
        k = r["name"].upper()
        if k not in groups:
            groups[k] = []
            order.append(k)
        groups[k].append(r)
    return [groups[k] for k in order]


