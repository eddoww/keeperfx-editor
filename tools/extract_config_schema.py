READ_RX = re.compile(r"get_conf_parameter_(single|whole)\s*\(\s*buf\s*,\s*&?\s*pos\s*,\s*len\s*,\s*([^,]+?)\s*,"
                     r"|recognize_conf_parameter\s*\(\s*buf\s*,\s*&?\s*pos\s*,\s*len\s*,\s*(\w+)\s*\)")
LOOKUP_RX = [
    (re.compile(r"get_long_id\s*\(\s*\(?[^,]*?(\w+)\s*,\s*DEST\b"), "enum"),
    (re.compile(r"get_r?id\s*\(\s*(\w+)\s*,\s*DEST\b"), "enum"),
    (re.compile(r"get_function_idx\s*\(\s*DEST\s*,\s*(\w+)"), "function"),
    (re.compile(r"parse_(creature)_name\s*\(\s*DEST\b"), "enum"),
]
SIMPLE_RX = [
    (re.compile(r"get_anim_id_?\s*\(\s*DEST\b"), "anim"),
    (re.compile(r"get_icon_id\s*\(\s*DEST\b"), "icon"),
    (re.compile(r"effect_or_effect_element_id\s*\(\s*DEST\b"), "effect_or_element"),
    (re.compile(r"get_string_id_by_alias\s*\(\s*DEST\b"), "stringid"),
    (re.compile(r"(?:sound_id_from_text|get_sound_id)\s*\(\s*DEST\b"), "sound"),
    (re.compile(r"speech_ref_parse\s*\([^,;]*,\s*DEST\b"), "speech"),
    (re.compile(r"\b(?:atoi|atol|atoll|strtol|strtoul)\s*\(\s*DEST\b"), "int"),
    (re.compile(r"(?:snprintf|strncpy|strcpy|strncat)\s*\([^;]*\bDEST\b"), "string"),
]


def find_loops(body):
    loops = []
    for m in re.finditer(r"\b(while|for)\s*\(", body):
        ps = m.end() - 1
        pe = match_bracket(body, ps, "(", ")")
        if pe < 0:
            continue
        j = pe + 1
        while j < len(body) and body[j].isspace():
            j += 1
        if j < len(body) and body[j] == "{":
            be = match_bracket(body, j)
        else:
            be = body.find(";", j)
        bound = None
        if m.group(1) == "for":
            bm = re.search(r";\s*\w+\s*<\s*([^;]+?)\s*;", body[ps + 1:pe])
            if bm:
                bound = bm.group(1).strip()
        loops.append({"kind": m.group(1), "cond": (ps, pe), "body": (j, be), "bound": bound})
    return loops


def infer_read_type(seg, dest, cmd_name):
    d = re.escape(dest)
    for rx, typ in LOOKUP_RX:
        m = re.search(rx.pattern.replace("DEST", d), seg)
        if m:
            return typ, m.group(1)
    for rx, typ in SIMPLE_RX:
        if re.search(rx.pattern.replace("DEST", d), seg):
            return typ, None
    if dest not in ("word_buf", "count_buf", "name_buf", "value_buf"):
        return ("name" if cmd_name.upper() == "NAME" else "string"), None
    return "unknown", None


def find_label(seg):
    m = re.search(r"(?:->|\.)(\w+)(?:\[[^\]]*\])*\s*(?:\|)?=(?!=)", seg)
    if m:
        return m.group(1)
    m = re.search(r"set_flag\s*\(\s*[\w\.\->\[\]]*?(?:->|\.)(\w+)", seg)
    if m:
        return m.group(1)
    return None


def find_range(seg, dest):
    am = re.search(r"\b(\w+)\s*=\s*(?:atoi|atol|atoll|strtol)\s*\(\s*" + re.escape(dest) + r"\b", seg)
    if not am:
        return None
    v = re.escape(am.group(1))
    m = re.search(r"if\s*\(\s*\(?\s*" + v + r"\s*(>=|>)\s*([^()&|]+?)\s*\)?\s*&&\s*\(?\s*" + v +
                  r"\s*(<=|<)\s*([^()&|]+?)\s*\)?\s*\)", seg)
    if not m:
        return None
    return m.group(1), m.group(2).strip(), m.group(3), m.group(4).strip()


def analyze_case_body(body, cmd_name, consts, tables_used):
    """Return (args, whole_line, notes) for one case body."""
    loops = find_loops(body)
    reads = list(READ_RX.finditer(body))
    args = []
    whole = False
    notes = []
    for idx, rm in enumerate(reads):
        seg_end = reads[idx + 1].start() if idx + 1 < len(reads) else len(body)
        seg = body[rm.start():seg_end]
        if rm.group(3):
            dest = "<param>"
            typ, table = "enum", rm.group(3)
        else:
            dest = rm.group(2).strip().lstrip("&")
            if rm.group(1) == "whole":
                whole = True
            typ, table = infer_read_type(seg, dest, cmd_name)
        if table == "creature" and typ == "enum":
            table = "creature_desc"
        a = OrderedDict()
        if typ in ("enum", "function") and table:
            a.update(arg_from_table(table, consts, tables_used))
            a["type"] = typ
        elif typ == "sound":
            a["type"] = "ref"
            a["ref"] = "sound"
        elif typ == "speech":
            a["type"] = "enum"
            a["enum"] = "speech_desc"
            tables_used.add("speech_desc")
            notes.append("speech_note")
        else:
            a["type"] = typ
        rng = find_range(seg, dest)
        if rng:
            op1, lo, op2, hi = rng
            lov, hiv = consts.eval(lo), consts.eval(hi)
            if lov is not None and op1 == ">":
                lov += 1
                lo = "(%s)+1" % lo if not is_plain_number(lo) else str(lov)
            if hiv is not None and op2 == "<":
                hiv -= 1
                hi = "(%s)-1" % hi if not is_plain_number(hi) else str(hiv)
            a["min"] = lov
            if not is_plain_number(lo):
                a["min_symbol"] = lo
            a["max"] = hiv
            if not is_plain_number(hi):
                a["max_symbol"] = hi
            if "range_note" not in notes:
                notes.append("range_note")
        lab = find_label(seg) if not re.search(r"\bswitch\b", seg) else None
        if lab:
            a["label"] = lab
        pos = rm.start()
        for lp in loops:
            in_cond = lp["kind"] == "while" and lp["cond"][0] <= pos <= lp["cond"][1]
            in_body = lp["body"][0] <= pos <= lp["body"][1]
            if in_cond or in_body:
                a["variadic"] = True
                bound = lp["bound"]
                if not bound:
                    nm = re.search(r"\bn\s*<\s*([A-Z_][A-Z0-9_]*)\b", body[lp["body"][0]:lp["body"][1]])
                    if nm:
                        bound = nm.group(1)
                if bound:
                    bv = consts.eval(bound)
                    if bv is not None:
                        a["max_count"] = bv
                if a["type"] == "enum" and re.search(r"\|=|set_flag\s*\(", seg):
                    a["type"] = "flags"
                break
        args.append(a)
    # collapse a variadic argument read several times in the same loop
    # reads that only happen in an else branch, or inside a nested switch, make the arity uncertain
    spans = []
    for em in re.finditer(r"\belse\b\s*", body):
        j = em.end()
        if j < len(body) and body[j] == "{":
            spans.append((j, match_bracket(body, j)))
        else:
            spans.append((j, body.find(";", j)))
    for sm in re.finditer(r"\bswitch\s*\([^)]*\)\s*\{", body):
        spans.append((sm.end() - 1, match_bracket(body, sm.end() - 1)))
    if any(a <= rm.start() <= b for rm in reads for (a, b) in spans):
        notes.append("branches")
    return args, whole, notes


def case_labels(body_text):
    """Yield (label_expr, start, end) for case/default labels at switch depth 0."""
    out = []
    depth = 0
    i = 0
    n = len(body_text)
    rx = re.compile(r"\b(case)\b\s*([^:]+?)\s*:(?!:)|\b(default)\s*:")
    while i < n:
        c = body_text[i]
        if c in "\"'":
            q = c
            i += 1
            while i < n and body_text[i] != q:
                if body_text[i] == "\\":
                    i += 1
                i += 1
            i += 1
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        elif depth == 0 and c in "cd":
            m = rx.match(body_text, i)
            if m and (i == 0 or not (body_text[i - 1].isalnum() or body_text[i - 1] == "_")):
                out.append((m.group(2) if m.group(1) else "default", i, m.end()))
                i = m.end()
                continue
        i += 1
    return out


def analyze_switch_function(cf, fname, consts, named, tables_used):
    """Analyze a block parser built on recognize_conf_command + switch."""
    f = cf.function(fname)
    if not f:
        return None
    fstart, bstart, bend = f
    text = cf.text
    body = text[bstart:bend]
    rm = re.search(r"recognize_conf_command\s*\(\s*buf\s*,\s*&?\s*pos\s*,\s*len\s*,\s*(\w+)\s*\)", body)
    if not rm:
        return None
    table = rm.group(1)
    tables_used.add(table)
    result = {"table": table, "function": fname, "loc": cf.loc(fstart)}
    bm = re.search(r"\bblock_name\s*=\s*\"([^\"]+)\"", body)
    nm = re.search(r"memcmp\s*\(\s*blockname\s*,\s*\"([^\"]+)\"", body)
    if nm:
        result["block"] = nm.group(1)
        result["numbered"] = True
        mx = re.search(r"\bi\s*>=\s*([A-Za-z_]\w*)\s*\)", body)
        if mx:
            result["max_symbol"] = mx.group(1)
            result["max"] = consts.eval(mx.group(1))
    elif bm:
        result["block"] = bm.group(1)
        result["numbered"] = False
    else:
        return None
    sm = re.search(r"switch\s*\(\s*cmd_num\s*\)\s*\{", body[rm.end():])
    cases = {}
    if sm:
        sw_open = bstart + rm.end() + sm.end() - 1
        sw_close = match_bracket(text, sw_open)
        sw_body = text[sw_open + 1:sw_close]
        labels = case_labels(sw_body)
        tinfo = named.get(table)
        entries = tinfo["entries"] if tinfo else []
        pending = []
        for li, (lab, ls, le) in enumerate(labels):
            nxt = labels[li + 1][1] if li + 1 < len(labels) else len(sw_body)
            pending.append(lab)
            stmt = sw_body[le:nxt]
            if not stmt.strip():
                continue
            for lab2 in pending:
                if lab2 == "default":
                    continue
                labv = consts.eval(lab2)
                for (en, ex, ev) in entries:
                    if ex == " ".join(lab2.split()) or (labv is not None and ev == labv):
                        cases.setdefault(en.upper(), (stmt, sw_open + 1 + le, en))
            pending = []
        result["switch_loc"] = cf.loc(sw_open)
    result["cases"] = cases
    return result


def switch_section(an, consts, named, tables_used):
    """Turn an analyzed switch parser into a section dict."""
    sec = OrderedDict()
    sec["name"] = an["block"]
    sec["numbered"] = an["numbered"]
    if an["numbered"]:
        if an.get("max") is not None:
            sec["max"] = an["max"]
        if an.get("max_symbol"):
            sec["max_symbol"] = an["max_symbol"]
    sec["source"] = an["loc"]
    sec["list"] = None
    keys = []
    tinfo = named.get(an["table"])
    seen = set()
    for (en, ex, ev) in (tinfo["entries"] if tinfo else []):
        if en.upper() in seen:
            continue
        seen.add(en.upper())
        key = OrderedDict()
        key["name"] = en
        key["whole_line"] = False
        key["repeat"] = False
        case = an["cases"].get(en.upper())
        notes = []
        if case is None:
            key["args"] = []
            key["ignored"] = True
            notes.append("Listed in %s but the parser has no case for it (it is reported as an unrecognized command)." % an["table"])
            key["source"] = tinfo["loc"] if tinfo else an["loc"]
        else:
            stmt, off, _ = case
            args, whole, cnotes = analyze_case_body(stmt, en, consts, tables_used)
            if not args and re.match(r"^\s*(break\s*;)?\s*$", stmt):
                key["ignored"] = True
                notes.append("Accepted but ignored by the parser.")
            key["whole_line"] = whole
            key["args"] = args
            key["source"] = an["file"].loc(off)
            if "branches" in cnotes:
                notes.append("The parser has alternative branches; the argument list is an approximation.")
            if "speech_note" in cnotes:
                notes.append("Speech message number, speech message name, or an audio file path.")
            if "range_note" in cnotes:
                notes.append("Numbers outside min..max are rejected (value ignored with a warning).")
        key["parse"] = None
        key["assign"] = None
        if notes:
            key["_cdoc"] = " ".join(notes)
        key["confidence"] = "partial"
        keys.append(key)
    sec["keys"] = keys
    return sec


