CAST_RE = re.compile(
    r"\(\s*(?:const\s+)?(?:unsigned\s+|signed\s+)?(?:long\s+long|long|short|int|char|"
    r"u?int(?:8|16|32|64)_t|size_t|ptrdiff_t|TbBool|ThingModel|ushort|uchar|ulong)\s*\)")


class Consts:
    def __init__(self, src_root):
        self.exprs = {}
        self.cache = {}
        files = sorted(p for p in src_root.rglob("*") if p.suffix in (".h", ".c") and p.is_file())
        define_rx = re.compile(r"(?m)^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)(?![\w(])[ \t]*(.*?)[ \t]*$")
        enum_rx = re.compile(r"\benum\b\s*(\w+)?\s*\{")
        for p in files:
            try:
                raw = p.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            text = strip_c_comments(raw)
            for m in define_rx.finditer(text):
                name, val = m.group(1), m.group(2).strip()
                if val.endswith("\\") or not val:
                    continue
                self.exprs.setdefault(name, val)
            for m in enum_rx.finditer(text):
                start = m.end() - 1
                end = match_bracket(text, start)
                if end < 0:
                    continue
                body = "\n".join(l for l in text[start + 1:end].split("\n") if not l.strip().startswith("#"))
                prev = None
                for part in split_top_level(body):
                    if not part:
                        continue
                    if "=" in part:
                        name, val = part.split("=", 1)
                        name, val = name.strip(), val.strip()
                    else:
                        name = part.strip()
                        val = "(%s)+1" % prev if prev else "0"
                    if re.match(r"^[A-Za-z_]\w*$", name):
                        self.exprs.setdefault(name, val)
                        prev = name

    def value(self, name, _depth=0):
        if name in BUILTIN_CONSTS:
            return BUILTIN_CONSTS[name]
        if name in self.cache:
            return self.cache[name]
        if name not in self.exprs or _depth > 40:
            return None
        self.cache[name] = None  # recursion guard
        v = self.eval(self.exprs[name], _depth + 1)
        self.cache[name] = v
        return v

    def eval(self, expr, _depth=0):
        if expr is None:
            return None
        e = expr.strip()
        if not e:
            return None
        if "sizeof" in e or '"' in e:
            return None
        e = CAST_RE.sub(" ", e)
        e = re.sub(r"'(\\?.)'", lambda m: str(ord(m.group(1)[-1])), e)
        e = re.sub(r"\b(0[xX][0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", e)
        e = e.replace("&&", " and ").replace("||", " or ")
        e = re.sub(r"!(?!=)", " not ", e)
        e = re.sub(r"(?<![/])/(?![/])", "//", e)
        try:
            tree = ast.parse(e, mode="eval")
        except SyntaxError:
            return None

        def ev(node):
            if isinstance(node, ast.Expression):
                return ev(node.body)
            if isinstance(node, ast.Constant) and isinstance(node.value, int):
                return int(node.value)
            if isinstance(node, ast.Name):
                v = self.value(node.id, _depth)
                if v is None:
                    raise ValueError(node.id)
                return v
            if isinstance(node, ast.UnaryOp):
                v = ev(node.operand)
                if isinstance(node.op, ast.USub):
                    return -v
                if isinstance(node.op, ast.UAdd):
                    return v
                if isinstance(node.op, ast.Invert):
                    return ~v
                if isinstance(node.op, ast.Not):
                    return int(not v)
            if isinstance(node, ast.BinOp):
                a, b = ev(node.left), ev(node.right)
                ops = {ast.Add: lambda: a + b, ast.Sub: lambda: a - b, ast.Mult: lambda: a * b,
                       ast.FloorDiv: lambda: int(a / b), ast.Mod: lambda: a % b,
                       ast.LShift: lambda: a << b, ast.RShift: lambda: a >> b,
                       ast.BitOr: lambda: a | b, ast.BitAnd: lambda: a & b, ast.BitXor: lambda: a ^ b}
                for k, f in ops.items():
                    if isinstance(node.op, k):
                        return f()
            if isinstance(node, ast.BoolOp):
                vals = [ev(v) for v in node.values]
                if isinstance(node.op, ast.And):
                    return int(all(vals))
                return int(any(vals))
            if isinstance(node, ast.Compare) and len(node.ops) == 1:
                a, b = ev(node.left), ev(node.comparators[0])
                op = node.ops[0]
                table = {ast.Lt: a < b, ast.LtE: a <= b, ast.Gt: a > b, ast.GtE: a >= b,
                         ast.Eq: a == b, ast.NotEq: a != b}
                for k, v in table.items():
                    if isinstance(op, k):
                        return int(v)
            if isinstance(node, ast.IfExp):
                return ev(node.body) if ev(node.test) else ev(node.orelse)
            raise ValueError("unsupported")

        try:
            return ev(tree)
        except (ValueError, ZeroDivisionError, RecursionError, TypeError):
            return None


def is_plain_number(text):
    return bool(re.match(r"^-?\s*(0[xX][0-9a-fA-F]+|\d+)[uUlL]*$", text.strip()))


def number_with_symbol(consts, text, key_num, key_sym, target):
    """Store resolved number and the symbolic text (when not a plain number)."""
    if text is None:
        return
    t = " ".join(text.split())
    v = consts.eval(t)
    target[key_num] = v
    if not is_plain_number(t):
        target[key_sym] = t


