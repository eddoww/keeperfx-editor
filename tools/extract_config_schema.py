# Only these pages document config keys; other pages (level script) reuse key-like words.
WIKI_KEY_PAGES = ("Custom-Configuration-files.md", "How-to-add-custom-Creatures.md")


def wiki_docs(wiki_dir, file_names, key_index):
    """Return (file_docs, key_docs) from the wiki markdown."""
    file_docs = {}
    key_docs = {}
    if not wiki_dir.is_dir():
        return file_docs, key_docs
    cfg_page = wiki_dir / "Custom-Configuration-files.md"
    if cfg_page.is_file():
        text = read_text(cfg_page)
        for line in text.splitlines():
            m = re.match(r"^\d+\)\s+(.*)$", line.strip())
            if not m:
                continue
            body = m.group(1).strip()
            for fn in re.findall(r"([A-Za-z_]+\.(?:cfg|toml))", body):
                if fn in file_names:
                    file_docs.setdefault(fn, []).append(clean_md(body))
        sec = re.search(r"### 4\.1 Unit configs\s*\n(.*?)\n\n(.*?)\n\n", text, re.S)
        if sec:
            file_docs.setdefault("creatrs/*.cfg", []).append(clean_md(sec.group(1) + " " + sec.group(2)))
        part = re.search(r"## 2\. How config files get stacked\.\s*\n\s*\n(.*?)\n\n", text, re.S)
        if part:
            file_docs.setdefault("*", []).append(clean_md(part.group(1)))
    for page in sorted(wiki_dir.glob("*.md")):
        if page.name not in WIKI_KEY_PAGES:
            continue
        text = re.sub(r"```.*?```", "", read_text(page), flags=re.S)
        for para in re.split(r"\n\s*\n", text):
            files_in = set(re.findall(r"([A-Za-z_]+\.(?:cfg|toml))", para))
            for tok in re.findall(r"`([A-Za-z_][\w]*)\s*=?\s*`", para):
                cands = key_index.get(tok.upper(), [])
                if not cands or len(tok) < 4:
                    continue
                files = sorted(set(c[0] for c in cands))
                pick = None
                if len(files) == 1:
                    pick = files[0]
                else:
                    hits = [f for f in files if f in files_in or (f == "creatrs/*.cfg" and any(
                        x.endswith(".cfg") and x not in file_names for x in files_in))]
                    if len(hits) == 1:
                        pick = hits[0]
                if pick:
                    for c in cands:
                        if c[0] == pick:
                            key_docs.setdefault((pick, c[1], tok.upper()), []).append(
                                "%s (wiki: %s)" % (clean_md(para)[:600], page.stem))
    return file_docs, key_docs


def clean_md(s):
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s)
    s = re.sub(r"\*\*|\*\*\*", "", s)
    s = re.sub(r"```.*?```", "", s, flags=re.S)
    return " ".join(s.split())


