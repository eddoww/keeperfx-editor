def strip_c_comments(text):
    """Blank out comments (keeping newlines and offsets); keep string literals."""
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"' or c == "'":
            q = c
            j = i + 1
            while j < n and text[j] != q:
                if text[j] == "\\":
                    j += 1
                elif text[j] == "\n":
                    break
                j += 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            if j < 0:
                j = n
            out.append(" " * (j - i))
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append("".join(ch if ch == "\n" else " " for ch in text[i:j]))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def match_bracket(text, pos, open_ch="{", close_ch="}"):
    """text[pos] == open_ch; return index of the matching close_ch."""
    depth = 0
    i = pos
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"' or c == "'":
            q = c
            i += 1
            while i < n and text[i] != q:
                if text[i] == "\\":
                    i += 1
                i += 1
        elif c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return -1


def split_top_level(text, sep=","):
    parts = []
    depth = 0
    cur = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"' or c == "'":
            q = c
            j = i + 1
            while j < n and text[j] != q:
                if text[j] == "\\":
                    j += 1
                j += 1
            cur.append(text[i:j + 1])
            i = j + 1
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == sep and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    tail = "".join(cur).strip()
    if tail:
        parts.append(tail)
    return parts


class CFile:
    def __init__(self, root, rel):
        self.rel = rel
        self.raw = (root / rel).read_text(encoding="utf-8", errors="replace")
        self.text = strip_c_comments(self.raw)
        self.nl = [i for i, c in enumerate(self.raw) if c == "\n"]

    def line(self, offset):
        return bisect.bisect_left(self.nl, offset) + 1

    def loc(self, offset):
        return "%s:%d" % (self.rel, self.line(offset))

    def function(self, name):
        """Return (body_start, body_end) offsets of a function definition."""
        rx = re.compile(r"(?m)^[A-Za-z_][\w \t\*]*\b" + re.escape(name) + r"\s*\(([^;{}]*)\)\s*\{")
        for m in rx.finditer(self.text):
            start = m.end() - 1
            end = match_bracket(self.text, start)
            if end > 0:
                return m.start(), start, end
        return None


