def parse_cfg_doc(text):
    """Return list of (section, key, values, doc_above, line) and section docs."""
    out_keys = []
    sec_docs = {}
    section = None
    pending = []
    for ln, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s:
            pending = []
            continue
        if s.startswith(";") or s.startswith("#"):
            pending.append(s.lstrip(";#").strip())
            continue
        if s.startswith("["):
            m = re.match(r"^\[([^\]]+)\]\s*(?:[;#]\s*(.*))?$", s)
            if m:
                section = m.group(1).strip()
                d = [x for x in pending if x]
                if m.group(2):
                    d.append(m.group(2).strip())
                sec_docs.setdefault(section, []).append("\n".join(d))
            pending = []
            continue
        m = re.match(r"^([A-Za-z_][\w]*)\s*=?\s*(.*)$", s)
        if m and section is not None:
            val = re.split(r"\s;", m.group(2))[0].strip()
            out_keys.append((section, m.group(1), val, "\n".join(x for x in pending if x), ln))
        pending = []
    return out_keys, sec_docs


def parse_toml_doc(text):
    """Very small TOML reader: tables, arrays of tables, key = value (multi-line arrays), # comments."""
    out_keys = []
    sec_docs = {}
    section = None
    pending = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        raw = lines[i]
        s = raw.strip()
        ln = i + 1
        i += 1
        if not s:
            pending = []
            continue
        if s.startswith("#"):
            pending.append(s.lstrip("#").strip())
            continue
        m = re.match(r"^(\[\[?)\s*([^\]]+?)\s*\]\]?\s*(?:#\s*(.*))?$", s)
        if m:
            section = m.group(2)
            d = [x for x in pending if x]
            if m.group(3):
                d.append(m.group(3))
            sec_docs.setdefault(section, []).append("\n".join(d))
            pending = []
            continue
        m = re.match(r"^([A-Za-z_][\w\-]*)\s*=\s*(.*)$", s)
        if m:
            val = m.group(2)
            depth = val.count("[") - val.count("]")
            while depth > 0 and i < len(lines):
                nxt = lines[i].split("#")[0]
                val += " " + nxt.strip()
                depth += nxt.count("[") - nxt.count("]")
                i += 1
            val = re.sub(r"\s#.*$", "", val) if not val.startswith("[") else val
            out_keys.append((section, m.group(1), val.strip(), "\n".join(x for x in pending if x), ln))
        pending = []
    return out_keys, sec_docs


def split_numbered(name):
    m = re.match(r"^(.*?)(\d+)$", name)
    if m and m.group(1):
        return m.group(1), int(m.group(2))
    return name, None


def guess_cfg_args(values):
    """Guess argument types from the values seen for an unknown key."""
    toks_list = [v.split() for v in values if v.strip()]
    if not toks_list:
        return [A("unknown")]
    n = max(len(t) for t in toks_list)
    args = []
    for i in range(n):
        col = [t[i] for t in toks_list if len(t) > i]
        if all(re.match(r"^-?\d+$", c) for c in col):
            args.append(A("int"))
        else:
            args.append(A("string"))
    return args


def guess_toml_args(values):
    vals = [v for v in values if v]
    if not vals:
        return [A("unknown")], {}
    if all(v.startswith("[") for v in vals):
        inner = " ".join(vals)
        if re.search(r"\"", inner):
            return [A("string")], {"array": True}
        return [A("int")], {"array": True}
    if all(v in ("true", "false") for v in vals):
        return [A("bool")], {}
    if all(re.match(r"^-?\d+$", v) for v in vals):
        return [A("int")], {}
    return [A("string")], {}


def best_doc(docs):
    docs = [d for d in docs if d and d.strip()]
    if not docs:
        return None
    c = Counter(docs)
    best = max(c.values())
    for d in docs:  # first in file order among the most common
        if c[d] == best:
            return d
    return None


