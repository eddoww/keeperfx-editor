def cfg_sections_from_loader(cf, load_func, consts, named, nf_tables, nf_sets, tables_used, synth_enums):
    f = cf.function(load_func)
    if not f:
        raise SystemExit("load function %s not found in %s" % (load_func, cf.rel))
    fstart, bstart, bend = f
    body = cf.text[bstart:bend]
    sections = []
    call_rx = re.compile(r"\b(parse_named_field_blocks?|\w+)\s*\(")
    for m in call_rx.finditer(body):
        fn = m.group(1)
        if fn in ("if", "while", "for", "switch", "sizeof", "return"):
            continue
        ps = m.end() - 1
        pe = match_bracket(body, ps, "(", ")")
        argtxt = body[ps + 1:pe]
        args = split_top_level(argtxt)
        if fn == "parse_named_field_block":
            block = args[4].strip('"')
            tname = args[5]
            if any(s["name"] == block and not s["numbered"] for s in sections):
                continue
            sec = OrderedDict()
            sec["name"] = block
            sec["numbered"] = False
            sec["source"] = nf_tables[tname]["loc"]
            sec["list"] = None
            sec["keys"] = [namedfield_key(g, consts, named, tables_used, cf, synth_enums)
                           for g in group_rows(nf_tables[tname]["rows"])]
            sec["override"] = "per_key"
            sections.append(sec)
        elif fn == "parse_named_field_blocks":
            sname = args[4].lstrip("&")
            s = nf_sets[sname]
            sec = OrderedDict()
            sec["name"] = s["basename"]
            sec["numbered"] = True
            number_with_symbol(consts, s["max"], "max", "max_symbol", sec)
            sec["source"] = s["loc"]
            sec["list"] = None
            sec["keys"] = [namedfield_key(g, consts, named, tables_used, cf, synth_enums)
                           for g in group_rows(nf_tables[s["fields"]]["rows"])]
            if s["names"] not in ("NULL", "0"):
                tables_used.add(s["names"])
                sec["names_enum"] = s["names"]
            sec["override"] = ("per_key: a full (non-partial) load first resets every item to the table defaults; "
                               "a partial layer only changes the keys it contains")
            sections.append(sec)
        elif "buf" in [a.strip() for a in args]:
            an = analyze_switch_function(cf, fn, consts, named, tables_used)
            if an:
                an["file"] = cf
                sections.append(switch_section(an, consts, named, tables_used))
    return sections


