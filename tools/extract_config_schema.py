def parse_namedfield_tables(cf):
    tables = {}
    rx = re.compile(r"struct\s+NamedField\s+(\w+)\s*\[\s*\]\s*=\s*\{")
    for m in rx.finditer(cf.text):
        start = m.end() - 1
        end = match_bracket(cf.text, start)
        rows = []
        i = start + 1
        while i < end:
            if cf.text[i] == "{":
                j = match_bracket(cf.text, i)
                inner = cf.text[i + 1:j]
                toks = split_top_level(inner)
                if not toks or toks[0] == "NULL":
                    break
                if re.match(r"^(field_t|field_a|field)\s*\(", toks[2]):
                    fld = toks[2]
                    ctype = None
                    rest = toks[3:]
                else:
                    fld = toks[2]
                    ctype = toks[3]
                    rest = toks[4:]
                while len(rest) < 6:
                    rest.append("NULL")
                fm = re.match(r"^field_[ta]?\s*\(\s*(?:struct\s+)?(\w+)\s*,\s*([^,]+?)\s*(?:,\s*([^)]+))?\)$", fld)
                member = None
                if fm:
                    member = fm.group(2).strip()
                    if fm.group(3):
                        member += "[%s]" % fm.group(3).strip()
                else:
                    mm = re.search(r"offsetof\s*\(\s*struct\s+\w+\s*,\s*([\w\.\[\]]+)", fld)
                    if mm:
                        member = mm.group(1)
                rows.append({
                    "name": toks[0].strip('"'), "argnum": toks[1].strip(), "member": member,
                    "default": rest[0], "min": rest[1], "max": rest[2], "named": rest[3],
                    "parse": rest[4], "assign": rest[5], "loc": cf.loc(i), "offset": i,
                })
                i = j + 1
            else:
                i += 1
        tables[m.group(1)] = {"rows": rows, "loc": cf.loc(m.start())}
    return tables


def parse_namedfieldsets(cf):
    sets = {}
    rx = re.compile(r"struct\s+NamedFieldSet\s+(\w+)\s*=\s*\{")
    for m in rx.finditer(cf.text):
        start = m.end() - 1
        end = match_bracket(cf.text, start)
        toks = split_top_level(cf.text[start + 1:end])
        sets[m.group(1)] = {
            "basename": toks[1].strip('"'), "fields": toks[2], "names": toks[3],
            "max": toks[4], "loc": cf.loc(m.start()),
        }
    return sets


