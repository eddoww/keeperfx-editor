#!/usr/bin/env python3
"""Generate the static tables of kfx-gfx from the KeeperFX C sources.

Regenerate (from the repository root; KFX_SOURCE is a checkout of the KeeperFX C repository):

    python3 -I tools/gen_gfx_tables.py "$KFX_SOURCE" crates/kfx-gfx/src

Reads (read only):
  src/creature_graphics.c  creature_list[]  (animation id -> first creature.tab index)
  src/creature_graphics.h  CREATURE_FRAMELIST_LENGTH
  src/sprites.h            enum GUIButtonSprite / GUIPanelSprite / GUIFrontendSprite

Writes <src dir>/gen_creature_list.rs and <src dir>/gen_sprite_names.rs.
Standard library only.
"""
import re
import sys
from pathlib import Path


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_gfx_tables.py <keeperfx_source> <kfx-gfx src dir>")
    root, out = Path(sys.argv[1]), Path(sys.argv[2])
    c = (root / "src/creature_graphics.c").read_text()
    h = (root / "src/creature_graphics.h").read_text()
    n = int(re.search(r"#define\s+CREATURE_FRAMELIST_LENGTH\s+(\d+)", h).group(1))
    m = re.search(r"creature_list\[CREATURE_FRAMELIST_LENGTH\]\s*=\s*\{(.*?)\};", c, re.S)
    vals = [int(x) for x in re.findall(r"\d+", m.group(1))]
    if len(vals) != n:
        sys.exit(f"creature_list has {len(vals)} entries, expected {n}")
    with open(out / "gen_creature_list.rs", "w") as f:
        f.write("// @generated by tools/gen_gfx_tables.py from src/creature_graphics.c creature_list[]. Do not edit.\n")
        f.write("/// Animation id -> index of its first frame in creature.tab (src/creature_graphics.c:51-159).\n")
        f.write(f"pub const CREATURE_LIST: [u16; {n}] = [\n")
        for i in range(0, n, 12):
            f.write("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",\n")
        f.write("];\n")

    s = (root / "src/sprites.h").read_text()
    enums = [("GUIButtonSprite", "GBS_BUTTON_SPRITES", "gui1-64"),
             ("GUIPanelSprite", "GPS_PANEL_SPRITES", "gui2-64"),
             ("GUIFrontendSprite", "GFS_FRONTEND_SPRITES", "frontend-64")]
    with open(out / "gen_sprite_names.rs", "w") as f:
        f.write("// @generated by tools/gen_gfx_tables.py from src/sprites.h. Do not edit.\n")
        for ename, const, sheet in enums:
            body = re.search(r"enum\s+" + ename + r"\s*\{(.*?)\};", s, re.S).group(1)
            body = re.sub(r"//[^\n]*", "", body)
            entries = []
            cur = -1
            for item in body.split(","):
                item = item.strip()
                if not item:
                    continue
                mm = re.match(r"(\w+)\s*(?:=\s*(\d+))?$", item)
                if not mm:
                    sys.exit(f"cannot parse enum item {item!r}")
                cur = int(mm.group(2)) if mm.group(2) is not None else cur + 1
                entries.append((mm.group(1), cur))
            f.write(f"/// `{ename}` constants for sheet `{sheet}` (sprites.h), in source order.\n")
            f.write(f"pub const {const}: [(&str, u16); {len(entries)}] = [\n")
            for name, v in entries:
                f.write(f'    ("{name}", {v}),\n')
            f.write("];\n")


if __name__ == "__main__":
    main()
